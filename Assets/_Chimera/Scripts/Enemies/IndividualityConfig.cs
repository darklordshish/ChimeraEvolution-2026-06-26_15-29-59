using UnityEngine;

/// <summary>
/// РУБИЛЬНИК ИНДИВИДУАЛЬНОСТИ. Индивидуальность — это два компонента, которые тело вешает каждому NPC:
/// разброс особи (<see cref="SpawnVariance"/>: множители урона, HP, скорости) и личность
/// (<see cref="Personality"/>: храбрость, агрессия, любопытство, осторожность).
///
/// Галочка снята — особь СРЕДНЯЯ: множители разброса равны 1, черты характера берутся из середины своих
/// диапазонов. Сами диапазоны остаются ручками на компонентах и вернутся в игру вместе с галочкой.
///
/// ЗАЧЕМ ВЫКЛЮЧАТЬ: пока в игре нет анимаций, звука и эффектов, ощущение и баланс не настраиваются
/// (решение геймдизайнера 15.09), а разброс делает механику недетерминированной — один и тот же укус
/// бьёт на ±15%. Механику проверяют тесты, им нужна средняя особь.
///
/// ГДЕ: объект в сцене (тюнинг — объектом в сцену, правило проекта). Без объекта в сцене индивидуальность
/// ВКЛЮЧЕНА — как было до рубильника, чтобы отсутствие объекта не выключало фичу молча. Тесты ставят
/// <see cref="On"/> напрямую.
/// </summary>
[DefaultExecutionOrder(-1000)] // раньше особей: разброс и личность катаются в своём Awake
public class IndividualityConfig : MonoBehaviour
{
    [Tooltip("Индивидуальность особей: разброс урона/HP/скорости и личность. Снято — все особи средние.")]
    [SerializeField] bool individuality = true;

    /// <summary>Действующее состояние. Читают `SpawnVariance` и `Personality` в своём Awake.</summary>
    public static bool On = true;

    void Awake() => On = individuality;

    // правка галочки в Play сразу действует на НОВЫХ особей (уже живые откатаны в своём Awake)
    void OnValidate() { if (Application.isPlaying) On = individuality; }
}
