/// <summary>
/// Стиль лаборатории (B0.1, уточнение 25.10). Интерьер у обоих ОДИН — закрытый бункер:
/// зал 14×14 с обходом, сплошное перекрытие, арена/хирургия/клетки/отдых. Стиль меняет
/// только внешнюю оболочку и вход, а не комнаты, двери и число внутренних деталей.
/// <para>
/// Bastion — низкий наземный блокгауз: одна плита, общий кровельный пояс/парапет,
/// тяжёлая рама входа. InSlope — тот же интерьер у подножия кольца: сзади и по бокам
/// подпорные массы/скальная оболочка, толща портала, без пещерного лабиринта.
/// </para>
/// <para>
/// Auto — «по месту»: сначала пробуется полоса у кольца (там комплекс может быть только
/// InSlope), и лишь если годного места в полосе нет — открытый пол (Bastion).
/// Детерминировано: тот же сид даёт тот же стиль.
/// </para>
/// <para>
/// Порядок значений — контракт сериализации: 0 обязан остаться Bastion, иначе новое
/// поле <c>labStyle</c> у компонента из сцены (приходит нулём) сменит стиль молча.
/// </para>
/// </summary>
public enum LabStyle
{
    Bastion = 0,
    InSlope = 1,
    Auto = 2,
}
