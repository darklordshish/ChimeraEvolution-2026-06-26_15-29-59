using UnityEngine;

/// <summary>ПАСПОРТ ДЕТАЛИ: роль куска и его собственный цвет, если он задан. Вешает `MorphBuilder` на
/// созданную часть, читает `TintMixer` — так системы цвета узнают деталь по СМЫСЛУ, а не по имени.
/// Компонент, а не словарь в микшере: деталь живёт и умирает вместе со своим паспортом, поэтому после
/// пересборки тела ничего не протухает (прежние списки имён именно так и умирали — молча).</summary>
public class PartMark : MonoBehaviour
{
    public PartRole role;   // чем этот кусок является (глаз, ухо, ямка…)
    public Color own;       // своя окраска; alpha 0 = не задана — деталь красится по составу, как всё тело

    public Color tone;      // ТОН КОЖИ (рисунок Шкуры, спека 06.11): множитель к цвету по составу; alpha 0 = нет

    public bool HasOwn => own.a > 0f;
    public bool HasTone => tone.a > 0f;
}
