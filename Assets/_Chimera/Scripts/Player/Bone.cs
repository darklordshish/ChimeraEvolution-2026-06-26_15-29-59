using UnityEngine;

/// <summary>КОСТЬ — линейный примитив скелета (спека 2026-08-18).
///
/// ЧЕМ ОТЛИЧАЕТСЯ ОТ МЕСТА. Место описано габаритной коробкой в долях родителя — девять чисел, ни одно
/// из которых не анатомично: «scale.y 0.234 от калибра ноги» невозможно ни снять с референса, ни
/// проверить глазом. Кость описана ДЛИНОЙ И УГЛОМ, то есть ровно тем, что меряется по ортографиям и
/// фотографии в профиль. Отсюда и весь смысл перехода: правится то, что видно.
///
/// ОСЬ КОСТИ — ЛОКАЛЬНАЯ +Y: кость растёт от своего начала вверх, а `dir` разворачивает её куда нужно.
/// Поворот НАСЛЕДУЕТСЯ по цепи, поэтому «плечо → предплечье → пясть» задаётся углами В СУСТАВАХ, а не
/// абсолютными позициями: согнул плечо — поехала вся нога, и рассогласовать её нечем.</summary>
[System.Serializable]
public class Bone
{
    public string name;              // имя-адрес: по нему кость находят модули, правила и контракт имён частей
    public string parent;            // родительская кость («» у корня модуля)

    /// <summary>ТОЧКА СТАРТА КОРНЕВОЙ КОСТИ — метры от земли, в системе контейнера `Morph` (там же, где
    /// меряет карта тел). Читается ТОЛЬКО у корня цепи: у кости с родителем начало — это сустав, и своих
    /// координат у неё нет по построению.
    ///
    /// Эти три числа — единственные позиции во всём скелете, и существуют они ровно потому, что скелет
    /// пока ЧАСТИЧНЫЙ: нога и череп прототипа висят без корпуса, крепиться им не к чему. Когда на кости
    /// перейдёт позвоночник, `origin` останется у одного настоящего корня, а модули сядут на суставы.</summary>
    public Vector3 origin;

    /// <summary>КАКОМУ МОДУЛЮ ПРИНАДЛЕЖИТ КОСТЬ — имя слота аугумента («Руки», «Сердце», «Пасть»).
    ///
    /// Это и есть естественное деление тела: слот — единица химеризации, значит и единица скелета.
    /// Отсюда при скиннинге следует разбиение мешей — ОДИН `SkinnedMeshRenderer` на слот поверх общей
    /// иерархии костей: графт перестраивает меш своего модуля, а не всю тушу; имя рендерера совпадает с
    /// именем слота, и контракт имён частей продолжает работать без списков-исключений.
    ///
    /// НЕ ПУТАТЬ С ПОДАВЛЕНИЕМ ФОРМЫ. Принадлежность и «место больше не рисует себя» — разные вещи:
    /// челюсть принадлежит слоту «Пасть», но подавить место «Пасть» нельзя, вместе с ним исчезли бы зубы.
    /// Что скрывает скелет — сказано у вида одним списком (`SpeciesSO.skeletonHides`).</summary>
    public string socket;

    /// <summary>ГДЕ НА РОДИТЕЛЕ начинается эта кость: доля вдоль его длины. 1 = конец (обычный сустав),
    /// 0.5 = середина (так сидят рёбра на позвонке, скула на черепе).</summary>
    public float attach = 1f;

    /// <summary>ДЛИНА В МЕТРАХ — главное число кости. Снимается с референса напрямую.</summary>
    public float length = 0.1f;

    /// <summary>Углы поворота относительно родителя. Наследуются вниз по цепи.</summary>
    public Vector3 dir;

    // ТОЛЩИНА У КОНЦОВ. Разные `r0` и `r1` дают веретено вместо капсулы — именно этим силуэт перестаёт
    // быть «шариками»: кость сужается к суставу, мясо идёт конусом. Равные радиусы вернут ту же капсулу,
    // что и в парадигме мест, — это назван­ный в спеке риск, и лечится он здесь
    public float r0 = 0.05f;
    public float r1 = 0.05f;

    /// <summary>СЕЧЕНИЕ: ширина к глубине. 1 = круг, 0.5 = вдвое уже, чем глубже. Без этого корпус
    /// читается бочкой при любых длинах: у волка грудь анфас почти плоская (овал ~1:2).</summary>
    public float section = 1f;

    /// <summary>Сегментов, если кость составная: позвоночник, рёбра, хвост. 0/1 — цельная кость.</summary>
    public int chain;

    /// <summary>Пара зеркально по X — конечности, рёбра, скулы: одна запись даёт обе стороны.</summary>
    public bool mirrorX;
}
