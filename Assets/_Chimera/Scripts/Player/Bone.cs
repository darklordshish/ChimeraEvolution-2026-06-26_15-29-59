using UnityEngine;

/// <summary>СЛОЙ ТЕЛА — порядок, в котором зверь собирается, и порядок, в котором его принимают.
///
/// Пока всё лежало одним списком, нельзя было утвердить скелет отдельно от мяса: смотришь всегда на
/// итог и правишь симптом, а каждая правка силуэта ломает анатомию. Слои разводят это по шагам:
/// сперва кости (верна ли конструкция), потом мышцы (появился ли объём), потом шкура, потом признаки.</summary>
public enum BodyLayer
{
    /// <summary>Кость: длина и угол заданы, при движении меняет только положение.</summary>
    Skeleton = 0,
    /// <summary>Мышца: натянута между двумя костями, длину и угол не задают (см. `Bone.endBone`).</summary>
    Muscle = 1,
    /// <summary>Признак: ухо, мочка, надбровье — мелкая форма поверх готового тела.</summary>
    Feature = 2,
    /// <summary>ВЫЧИТАНИЕ: не добавляет объём, а ВЫРЕЗАЕТ его. Рот, ноздри, глазница — углубления,
    /// а не наросты. Без этого слоя пасть остаётся «затянутой»: щель нечем прорезать, можно только
    /// положить сверху ещё один объём, отчего морда и заплывает.</summary>
    Cut = 3,
}

/// <summary>КОСТЬ — линейный примитив скелета (спека 2026-08-18).
///
/// ЧЕМ ОТЛИЧАЕТСЯ ОТ МЕСТА. Место описано габаритной коробкой в долях родителя — девять чисел, ни одно
/// из которых не анатомично: «scale.y 0.234 от калибра ноги» невозможно ни снять с референса, ни
/// проверить глазом. Кость описана ДЛИНОЙ И УГЛОМ, то есть ровно тем, что меряется по ортографиям и
/// фотографии в профиль. Отсюда и весь смысл перехода: правится то, что видно.
///
/// ОСЬ КОСТИ — ЛОКАЛЬНАЯ +Y: кость растёт от своего начала вверх, а `dir` разворачивает её куда нужно.
/// Поворот НАСЛЕДУЕТСЯ по цепи, поэтому «плечо → предплечье → пясть» задаётся углами В СУСТАВАХ, а не
/// абсолютными позициями: согнул плечо — поехала вся нога, и рассогласовать её нечем.</summary>
[System.Serializable]
public class Bone
{
    /// <summary>ИМЯ-АДРЕС: по нему кость находят модули, правила, дети и мышцы. Формат — АНАТОМИЯ + СЛОЙ:
    /// `.м` мышца, `.п` признак, `.р` рез; скелет без суффикса, он основа и на его имена ссылаются.
    ///
    /// Суффикс не косметика. Одна анатомическая единица живёт сразу в нескольких слоях — есть кость
    /// скулы и мясо скулы, есть ветвь челюсти и жевательная поверх неё, — и пока слой в имя не входил,
    /// такие соседи сталкивались адресами МОЛЧА: словарь оставлял последнюю, первая теряла позицию, а
    /// ссылавшиеся на неё дети уезжали в чужое место. Ошибки при этом нет нигде, ищется по перекошенной
    /// морде. Так и нашлось: «жевательная» была задана дважды.
    ///
    /// ЧЕГО СУФФИКС НЕ ЛЕЧИТ — описания одного тела дважды. Развести адреса значит лишь позволить обеим
    /// копиям спокойно рисоваться; поэтому генератор ОТДЕЛЬНО предупреждает о повторе анатомического
    /// имени между слоями: «проверь, не описано ли одно и то же и объёмом, и мышцей».</summary>
    public string name;
    public string parent;            // родительская кость («» у корня модуля)

    /// <summary>Слой сборки: кость, мышца, признак или вычитание. Он же порядок приёмки.</summary>
    public BodyLayer layer = BodyLayer.Skeleton;

    /// <summary>ТОЧКА СТАРТА КОРНЕВОЙ КОСТИ — метры от земли, в системе контейнера `Morph` (там же, где
    /// меряет карта тел). Читается ТОЛЬКО у корня цепи: у кости с родителем начало — это сустав, и своих
    /// координат у неё нет по построению.
    ///
    /// Эти три числа — единственные позиции во всём скелете, и существуют они ровно потому, что скелет
    /// пока ЧАСТИЧНЫЙ: нога и череп прототипа висят без корпуса, крепиться им не к чему. Когда на кости
    /// перейдёт позвоночник, `origin` останется у одного настоящего корня, а модули сядут на суставы.</summary>
    public Vector3 origin;

    /// <summary>КАКОМУ МОДУЛЮ ПРИНАДЛЕЖИТ КОСТЬ — имя слота аугумента («Руки», «Сердце», «Пасть»).
    ///
    /// Это и есть естественное деление тела: слот — единица химеризации, значит и единица скелета.
    /// Отсюда при скиннинге следует разбиение мешей — ОДИН `SkinnedMeshRenderer` на слот поверх общей
    /// иерархии костей: графт перестраивает меш своего модуля, а не всю тушу; имя рендерера совпадает с
    /// именем слота, и контракт имён частей продолжает работать без списков-исключений.
    ///
    /// НЕ ПУТАТЬ С ПОДАВЛЕНИЕМ ФОРМЫ. Принадлежность и «место больше не рисует себя» — разные вещи:
    /// челюсть принадлежит слоту «Пасть», но подавить место «Пасть» нельзя, вместе с ним исчезли бы зубы.
    /// Что скрывает скелет — сказано у вида одним списком (`SpeciesSO.skeletonHides`).</summary>
    public string socket;

    /// <summary>ГДЕ НА РОДИТЕЛЕ начинается эта кость: доля вдоль его длины. 1 = конец (обычный сустав),
    /// 0.5 = середина (так сидят рёбра на позвонке, скула на черепе).</summary>
    public float attach = 1f;

    /// <summary>ДЛИНА В МЕТРАХ — главное число кости. Снимается с референса напрямую.
    /// У МЫШЦЫ не задаётся: её длина есть расстояние между креплениями (см. `endBone`).</summary>
    public float length = 0.1f;

    /// <summary>МЫШЦА: к какой кости крепится ВТОРОЙ конец. Пусто — обычная кость.
    ///
    /// Разница принципиальная, и она вскрылась на волке. Кость при движении меняет только положение;
    /// мышца ещё и форму — она натянута между двумя точками и следует за обеими. Пока мы лепили мясо
    /// костями (трицепс, плечеголовная, горло), они висели на одном креплении: в анимации такая
    /// «мышца» поехала бы жёстко, а в данных её было не отличить от анатомии — и стало непонятно, что
    /// в силуэте от скелета, а что от нашей лепки.
    ///
    /// ДЛИНУ И УГОЛ МЫШЦЕ НЕ ЗАДАЮТ: они считаются из положения костей-креплений. Поэтому подвинул
    /// сустав — мышца подтянулась сама, и рассогласовать их нечем.</summary>
    public string endBone;

    /// <summary>Где на кости-цели крепится второй конец мышцы: доля вдоль её длины.</summary>
    public float endAttach = 1f;

    /// <summary>Углы поворота относительно родителя. Наследуются вниз по цепи.</summary>
    public Vector3 dir;

    // ТОЛЩИНА У КОНЦОВ. Разные `r0` и `r1` дают веретено вместо капсулы — именно этим силуэт перестаёт
    // быть «шариками»: кость сужается к суставу, мясо идёт конусом. Равные радиусы вернут ту же капсулу,
    // что и в парадигме мест, — это назван­ный в спеке риск, и лечится он здесь
    public float r0 = 0.05f;
    public float r1 = 0.05f;

    /// <summary>СЕЧЕНИЕ ПОПЕРЁК: множитель радиуса по ширине. 1 = круг, 0.5 = вдвое уже. Без этого корпус
    /// читается бочкой при любых длинах: у волка грудь анфас почти плоская (овал ~1:2).</summary>
    public float section = 1f;

    /// <summary>СЕЧЕНИЕ ВДОЛЬ ВЗГЛЯДА: множитель радиуса по глубине. Нужен там, где часть ПЛОСКАЯ и
    /// сплющена не по ширине, а по толщине: ухо, лопасть рога, плавник. Одним `section` такое не задать —
    /// он делает часть уже, а не тоньше, и ухо выходило бы валиком.</summary>
    public float depth = 1f;

    /// <summary>НАСКОЛЬКО ЭТА КОСТЬ СЛИВАЕТСЯ С СОСЕДЯМИ. 0 = взять общий для вида (`SpeciesSO.skinBlend`).
    ///
    /// Одного числа на всё тело не хватает, и это выяснилось на первом же звере: рёбрам слияние НУЖНО
    /// (иначе бок читается гофрой), а ноге — НЕТ. При общем 0.09 передняя нога сплавлялась с грудью в
    /// «юбку»: тело расширялось книзу (0.232 у верха груди против 0.320 на уровне плеча), хотя у волка
    /// наоборот. Конечности берут малое значение и остаются отдельными телами, корпус — большое.</summary>
    public float blend;

    /// <summary>Сегментов, если кость составная: позвоночник, рёбра, хвост. 0/1 — цельная кость.</summary>
    public int chain;

    /// <summary>Пара зеркально по X — конечности, рёбра, скулы: одна запись даёт обе стороны.</summary>
    public bool mirrorX;
}
