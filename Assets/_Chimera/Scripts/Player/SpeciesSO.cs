using UnityEngine;

/// <summary>
/// Вид/тело как данные — один ассет на вид («Человек», «Волк»). Две роли:
///  • ШАССИ — базовое тело: ёмкость пула + органы по умолчанию для каждого слота;
///  • ДОНОР — источник органов, которые ставятся в слоты шасси при химеризации.
/// Органы лежат внутри вида (не отдельными файлами). Готовит смену шасси и мультивид.
/// </summary>
[CreateAssetMenu(menuName = "Chimera/Вид (SpeciesSO)", fileName = "Species")]
public class SpeciesSO : ScriptableObject
{
    public string speciesName = "Вид";
    public Color tint = Color.gray;   // цвет тела при озверении этим видом (лерп шкалы мозга)
    public int mutagenPool = 10;      // ёмкость пула, когда вид = шасси
    public Organ[] organs;            // органы вида (по одному на покрываемый слот)
    public bool eatsMeat = true;      // ХИЩНИК: убил добычу → СЫТОСТЬ (бонус-реген). Травоядное (лось) — false:
                                      // волков не ест, добычей не восстанавливается (его еда — кормёжка по карте)
    public bool massive;              // МАССИВНАЯ ТУША (физ.свойство ШАССИ): обхват на стадию слабее, нокбэк не берёт, стае нужно больше.
                                      // В одном ряду с nativeChassis/мощью — характеристика тела, не принадлежность к виду. Тело вешает Massive-маркер

    // ВИТАЛЬНОСТЬ ШАССИ: сколько даёт ТЕЛО КАК ТАКОВОЕ, до всяких органов. Волк остаётся полноценным
    // волком и без выдающегося сердца; органы дают ПРОЦЕНТ сверху (Organ.hpBonus), а экспрессия
    // раскрывает бонус — но НЕ трогает базу. Иначе «Э 0.45» означало бы «полудохлый волк» (так и было).
    // 0 = не настроено → тело подставит дефолт (гоча нового поля в старом ассете; прогони бутстрап)
    public int baseHp = 0;

    // СТАМИНА — та же модель, что и HP: база тела + проценты от Сердца. Дыхалка вида: человек берёт
    // здесь (большой бак и лучший реген — его единственное превосходство над зверьём), лось — бак
    // без регена (туша прёт долго, отходит медленно), волк — середина.
    public int baseStamina = 0;
    public float baseStaminaRegen = 0f;

    // СОКЕТ-ПЛАН ТЕЛА (единый источник правды): места на теле. Имя сокета = `Organ.slot` — это И механика
    // (что можно надеть), И адрес визуала (где видно). Пусто = морфологии у вида нет (визуал префаба)
    public BodySocket[] sockets;

    // СКЕЛЕТ (спека 2026-08-18): кости живут РЯДОМ с сокет-планом, не заменяя его разом — у кого массив
    // пуст (четыре вида из пяти), сборка идёт по-старому до микрона. Каждая кость знает СВОЙ СЛОТ, и это
    // не украшение: слот — единица химеризации, поэтому он же станет единицей меша при скиннинге
    public Bone[] bones;

    // ЧТО СКЕЛЕТ РИСУЕТ ВМЕСТО МЕСТ. Перечисленные места сохраняют механику (имя = `Organ.slot`) и
    // остаются АДРЕСОМ И КАЛИБРОМ для своих детей — но собственную форму больше не строят, её строят кости.
    //     Отдельным списком, а не флагом у кости, потому что это свойство ВИДА, а не отдельной кости:
    // «Пасти» принадлежит челюсть, но подавлять место «Пасть» нельзя — вместе с ним исчезли бы зубы,
    // и найти такую пропажу можно было бы только глазами на скриншоте
    public string[] skeletonHides;
}

/// <summary>
/// Орган: вклад в статы своего слота (абсолютные значения; человеческие = базовая норма).
/// Каждый орган заполняет только «свои» статы, остальные = 0 — суммирование по слотам даёт итог.
/// </summary>
[System.Serializable]
public class Organ
{
    public string organName = "Орган";
    public string slot = "Руки";   // в какой слот шасси ставится
    public string hotkey = "1";    // временный бинд клавиши (MVP-конструктор)
    public int cost;               // цена в пуле

    public int damage, lifeSteal;
    public float staminaBonus;      // прибавка к БАКУ стамины, долей базы шасси (та же модель, что hpBonus)
    public float staminaRegenBonus; // прибавка к РЕГЕНУ стамины, долей базы шасси
    public float hpBonus;          // ПРИБАВКА К ВИТАЛЬНОСТИ ДОЛЕЙ базы шасси (0.5 = +50%), не абсолют.
                                   // Раньше было абсолютное `maxHp` — и оно не переносилось между телами
                                   // разного калибра: человеческое сердце в лосином шасси делало лося хилым
    public int venomStacks;        // яд на укусе (змеиные клыки): стаков за попадание
    public int bleedStacks;        // кровотечение на укусе (волчьи клыки): стаков за попадание
    public float range, atkCooldown, moveSpeed, dashSpeed, dashCooldown, damageReduction, regen, regenOOC;
    public float dashDuration;     // своя длина рывка ног (0 = дефолт контроллера): лосиные — длинный таран, волчьи — короткий
    public float thermalRange;     // радиус термозрения (Пит-орган); фикс-фича, как range — не блендится
    public float howlStunAt;       // ПОРОГ-ФИЧА (3-я ось экспрессии): мощь носителя ≥ этого — вой ещё и СТАНИТ.
                                   // 0 = стана нет вовсе. Не «сколько», а ЧТО ВООБЩЕ открывается: рядовой волк
                                   // (Э 0.45) только зовёт стаю, вервольф (Э 2) и игрок на 100 родства — глушат
    public float howlRadius;       // ГОЛОС Пасти: база радиуса воя (0 = не воет). Итог = база × мощь-превосходство
                                   // (тело считает: игрок BonusMult ×1..2, NPC max(1, Э) — норму вниз не штрафуем)
    public bool enablesBite, enablesScent, enablesKick, enablesHowl, coldBlooded, camo, enablesThermal, enablesConstrict;
    public bool thorns;            // ИГЛЫ (Шкура ежа): ответка на удар в упор + кровотечение обидчику
    public bool venomResist;       // ЯДОУПОРНОСТЬ (Сердце ежа): яд не накапливается — стак разлагается почти сразу
    public bool bleedResist;       // КРОВЕУПОРНОСТЬ (Лосиное сердце): кровь не накапливается — рана быстро затягивается
    public bool enablesQuillVolley; // ЗАЛП ИГЛАМИ (придаток «Игломёт» ежа, химерный слот — аддитивен, как Рога/Хвост):
                                    // ПЕРВЫЙ дальний бой игрока. Своя кнопка — дальний ≠ ближний, не делят слот-оружие
    public bool keenHearing;       // ОСТРЫЙ СЛУХ (лосиное Ухо): вдвое дальше + различение ВИДА источника
                                   // («Волк», а не «шум») + ВОЛНЫ ЗВУКА на экране. Слух отвечает «КТО шумит»,
                                   // Чутьё — «ЧТО происходит»: органы не пересекаются, вместе дают полную картину
    public float hearingMult;      // множитель дальности слуха (0 = ×1); у лосиного Уха ×2

    public bool insight;           // ЧУТЬЁ УЧЁНОГО (человеческое Чутьё): наблюдательность вместо звериного нюха —
                                   // РАСПОЗНАЁТ намерение по замаху (цвет приёма вместо «что-то готовит») и читает
                                   // состояния ЧИСЛОМ. Аналитика — сила человека: единственная фича этого слота,
                                   // за которую платят человечностью наоборот — сохранением её
    public bool enablesBellow;     // РЁВ (Глотка лося): детонация ярости на месте — кин-лоси в берсерк, чужих пугает
    public bool enablesScream;     // БОЕВОЙ КЛИЧ (Рот человека): ярость по СВОЕЙ крови — единственный голос,
                                   // направленный на себя. Волк воет — зовёт стаю, лось ревёт — пугает, а у
                                   // человека нет ни стаи, ни массы: его ход — заплатить собой
    public bool enablesAntler;     // РОГА (придаток лося, химерный слот): фронтальный удар — откидывание + кровотечение
    public bool enablesCharge;     // ТАРАН (Лосиные ноги): рывок становится горящим — урон+откидывание по пути («основа боя — копыта»)
    public bool enablesRoll;       // ПЕРЕКАТ (Ежиные ноги): рывок идёт «в клубке» — форма-кувырок с i-frames.
                                   // КОЛЕТСЯ только в связке с «Иглами» (Шкура): ноги дают форму, Шкура — жало
                                   // (кросс-слот сет §0-бис). Третий профиль ног после таранного и скоростного (§3-бис)
    public bool chassisOnly;       // ходовая часть/локомоция шасси: аугументом НЕ крадётся (закон: локомоция = свойство шасси)
    public bool digestion;         // ГЛОТАЕТ ЦЕЛИКОМ (тело змеи): убил → ПОЛНАЯ сытость (двойная), а не доля.
                                   // Лечение — общий `Satiety` (не отдельный компонент); ведёт в CreatureBody.DigestsWhole
    public string nativeChassis;   // РОДНОЕ ШАССИ приёма (2-я ось экспрессии): полная форма открыта только на этом шасси, на чужом — кап. Пусто = нет гейта.
                               // ЧТО ИМЕННО режется — дело приёма, а не флага: у Хвоста это стадия удушения (3 дома, 2 в гостях), у Ежиных ног — шар против кувырка.
                               // Огульно гейтить по нему ВСЕ дискретные фичи нельзя: у волчьей Пасти тоже `nativeChassis`, и вервольф остался бы без укуса
    public int constrictStage;     // РОДНАЯ сила захвата грэпл-органа (1–3): Хвост змеи 3, челюсти волка/ежа 1. Кап = нативен ? стадия : min(2, стадия). 0 = не грэпл-орган
    public bool enablesCurl;       // КЛУБОК (CurlDefense): свернуться в шар — броня↑, катание-таран. Носитель — ЕЖИНЫЕ НОГИ вместе с `enablesRoll`:
                               // одна способность на двух глубинах, вторую открывает `nativeChassis = "Ёж"`. Прежде висел на отдельном органе
                               // «Игольчатое тело» — том, что сидел на фиктивном месте `Тело` без единой детали (сущность ради флага)

    // МОРФОЛОГИЯ (ось 2): форма органа В ЕГО МЕСТЕ. МЕСТО ОТДЕЛЬНО НЕ ЗАДАЁТСЯ — это сокет с именем `slot`
    // (единый источник правды: механика и визуал не могут разойтись). Нет сокета под этот slot → орган невидим
    public Vector3 visualScale = Vector3.one; // габариты части (× baseSize сокета)
    public Vector3 visualOffset;              // локальное смещение от сокета
    public Vector3 visualEuler;               // локальный поворот
    public bool visualAlignToBody;            // ФОРМА ОРИЕНТИРУЕТСЯ ПО ТЕЛУ: части описаны в каноничном кадре
                                              // (X — поперёк, Y — НАРУЖУ от поверхности, Z — ВДОЛЬ тела), а сборщик
                                              // раскладывает их на реальные оси места: вдоль = длинная сторона,
                                              // наружу = короткая. Ежиный торс ЛЕЖИТ → щетина встаёт на спину;
                                              // человечий СТОИТ → та же щетина ложится гребнем вдоль позвоночника
    public OrganPart[] visualParts;           // СОСТАВНАЯ ФОРМА: орган из нескольких частей (рога = стебель +
                                              // лопасть + отростки; иглы = щетина). Пусто = одна деталь по полям выше
    public int visualSegments;                // СЕГМЕНТНОСТЬ органа (0/1 = одна деталь): змеиный хвост сегментен
                                              // ПО ПРИРОДЕ, где бы ни рос — обрубок как у волка врал бы о привитом.
                                              // Цепь идёт по ДЛИННОЙ стороне места: хвост тянется назад, рога вверх
    public float visualTaper;                 // сужение каждого следующего сегмента (0 = дефолт 0.85)
}

/// <summary>ЧАСТЬ СОСТАВНОЙ ФОРМЫ органа: рога = стебель + лопасть + отростки, иглы = щетина из шипов.
/// Смещение задаётся В КАЛИБРАХ МЕСТА (× baseSize сокета) — поэтому форма сама ужимается под мелкое шасси
/// и разрастается на крупном, оставаясь ОДНИМ описанием на все носители (закон «форма от органа»).</summary>
[System.Serializable]
public class OrganPart
{
    public Vector3 scale = Vector3.one; // габариты части (× размер места × visualScale органа)
    public Vector3 offset;              // смещение от места В КАЛИБРАХ (× baseSize сокета)
    public Vector3 euler;               // доворот части поверх поворота места и органа
    public PartShape shape;             // ГЕОМЕТРИЯ куска (по умолчанию куб — прежние данные не меняются)
    public PartRole role;               // РОЛЬ куска: по ней его находят слои цвета (глаз красится своим)
    public Color color;                 // СВОЯ ОКРАСКА (alpha 0 = не задана → цвет по составу, как у всех)
}

/// <summary>РОЛЬ КУСКА — по ней его адресуют слои цвета и маски эффектов. Раньше эту работу делали СПИСКИ
/// ИМЁН («EyeL/BrowR не красить составом», `Telegraph.IsHeadName`), и оба списка умерли молча: морф-части
/// именуются по СОКЕТАМ, таких имён у них нет вовсе. Роль живёт в данных рядом с формой — разойтись им
/// нечем, а новая роль не требует правок в системах, которые о ней не знают.</summary>
public enum PartRole { None = 0, Eye, Head, Ear, Nose, Pit }

/// <summary>ГЕОМЕТРИЯ куска. Куб держит силуэт (торс, череп, лопата рога), СФЕРА — сустав и всё круглое
/// (колено, нос, круп ежа), КАПСУЛА — кость со скруглёнными концами, ЦИЛИНДР — прямой стержень.
/// Одними кубами тело читается как штабель коробок; смесь примитивов снимает это почти даром.</summary>
public enum PartShape { Cube, Sphere, Capsule, Cylinder }

/// <summary>СОКЕТ — МЕСТО НА ТЕЛЕ (сокет-план, спека 2026-08-01): единая сущность для механики и морфологии.
/// Имя сокета = `Organ.slot`, поэтому «что можно надеть» и «где это видно» не могут разойтись. Позиции — под
/// РОСТ/ПОЗУ вида (человек прямоходящий, волк 4-ногий). Бывают чисто телесные места без органов (голова/шея/уши).</summary>
[System.Serializable]
public class BodySocket
{
    public string name;                    // ИМЯ = Organ.slot («Руки»/«Пасть»/«Хвост») ИЛИ телесное место («голова»/«шея»/«уши»)
    public Vector3 localPos;               // локальная позиция места на теле
    public Vector3 baseSize = Vector3.one; // базовый габарит места (часть масштабируется относительно него)
    public Vector3 baseEuler;              // наклон места (сутулая шея, хвост вверх, ухо ромбом) — форма позы шасси
    public bool mirrorX;                   // ПАРА: один якорь → две части зеркально по X (4 лапы/2 уха одной записью,
                                           // localPos.x = вынос вбок; иначе пара выглядела бы одним блоком)
    public bool codeDriven;

    // [ANIM] ПЛОТНАЯ ЧАСТЬ: коллайдер не снимается, кусок тела становится препятствием ДЛЯ ДРУГИХ и
    // поверхностью попаданий. Первой идёт змея (её тело плотное по всей длине — так было и в префабе),
    // но по решению пользователя это НАПРАВЛЕНИЕ для всех: столкновение и урон по реальной форме, а не
    // по одной капсуле на корне — «микро-динамика боя». ВАЖНО: своего носителя это НЕ останавливает —
    // движение ведёт CharacterController, и сталкивается он только своей капсулой (см. баг «лось головой
    // в стене»). После каждой пересборки носитель обязан заново гасить столкновение тела со своим CC
    public bool solid;
    public bool inner;                     // ВНУТРИ ТЕЛА: своего силуэта нет, но орган ПРОСТУПАЕТ формой.
                                           // Сердце даёт грудную клетку — у млекопитающих рёбра сходятся на грудине,
                                           // у змеи грудной клетки нет вовсе (рёбра по всей длине), и то же поле
                                           // даёт утолщение в передней трети. Одно поле, разный смысл по носителю
    public bool graft;                     // ЗАКРЫТ у этого шасси (плейсхолдер): пустым НЕ рисуется, только с органом.
                                           // У человека нет хвоста/рогов — но привил змеиный хвост или лосиные рога, и они видны
                                           // (от `inner` отличается смыслом: тут места у вида НЕТ, там оно есть, но внутри)

    // ── ГРАФ ХРЕБТА (спека 2026-08-05). Тело строится ОТ ПОЗВОНОЧНИКА: место с родителем не хранит своих
    // координат, билдер считает их сам и НАСЛЕДУЕТ ПОВОРОТ. Наклонил шею — голова, морда, уши и рога
    // поехали за ней. Раньше список был плоским, каждый стык считался вручную и разъезжался от любой правки
    public string parent;                  // имя места-родителя; пусто = корень (сегмент хребта, живёт по localPos)
    public float attach = 1f;              // ГДЕ на родителе стык: доля вдоль его ДЛИННОЙ оси (0 — начало, 1 — конец)
    public Vector3 attachOffset;           // доводка от точки стыка, В КАЛИБРАХ РОДИТЕЛЯ (не в метрах — переживает
                                           // масштабирование вида: увеличили волка ×1.5, смещения поехали следом)
    public OrganPart[] parts;              // ФОРМА САМОГО МЕСТА (силуэт шасси): торс = грудь+талия+круп, голова = череп+морда+нос.
                                           // Без неё туша обречена быть одним бруском — узнаваемости не выходит. Части — в ДОЛЯХ
                                           // `baseSize`, как у органа. Орган СО СВОЕЙ формой перебивает форму места

    // ── ЦЕПЬ ЗВЕНЬЕВ (спека 2026-08-05, п. 5–6). Место может быть НЕ ОДНИМ куском, а вереницей одинаковых
    // звеньев вдоль своей длинной оси: так устроено тело змеи. Спека предлагала завести места «Тело 1..N»
    // отдельными записями, но это ломает контракт «имя сокета = Organ.slot» — орган «Тело-хвост» (змея)
    // сидит на слоте «Тело» и перестал бы находить своё место. Поэтому длина цепи —
    // ЧИСЛО У МЕСТА: имя одно на все звенья, длина правится одной цифрой, дети крепятся к КОНЦУ цепи
    public int chain;                      // сколько звеньев (0/1 = обычное одиночное место)
    public float chainTaper;               // УСТАРЕЛО (масштабировал звено ЦЕЛИКОМ — сужение и укорочение были
                                           // одним числом). Живёт только ради органной цепи `visualSegments`

    // ── ЗВЕНО В МЕТРАХ (унификация). Раньше форма звена собиралась из ДОЛЕЙ `parts`, и длину приходилось
    // вычислять в уме: `baseSize.y × scale.y`, причём доля Z уходила не в длину, а в ВЫСОТУ. Отсюда весь
    // ворох промахов — эллипсоиды по вертикали, суставы-диски, звенья разной длины. Теперь звено задаётся
    // ДВУМЯ ЧИСЛАМИ, а капсулу с суставом строит билдер: согласовывать в уме больше нечего.
    // `linkLength` ОДИН НА ВСЮ ЦЕПЬ — равная длина звеньев выходит ПО ПОСТРОЕНИЮ, а не подбором
    // ДИАМЕТР МОЖНО НЕ ЗАДАВАТЬ: пустой (0) при заданной `linkLength` = ПРОДОЛЖИТЬ РОДИТЕЛЬСКУЮ ЦЕПЬ с того
    // диаметра, каким она кончилась (тело подхватывает шею, хвост — тело). Стыку нечем разойтись: число
    // живёт в одном месте и выводится дальше, а не переписывается руками в каждом звене вереницы
    public float linkDiameter;             // толщина ПЕРВОГО звена, метры (0 = наследовать от родителя)
    // ГАБАРИТ В ДОЛЯХ РОДИТЕЛЯ — «шасси говорит КАК вставлять». Абсолютные метры у каждого места жили
    // сами по себе, и правка одного молча ломала соседей: сузили череп — рога съехались внутрь; вырос
    // корпус — голова осталась мелкой; поджали голову — пасть стала длиннее морды. Ошибок нет ни в одном
    // случае, просто силуэт врёт, и ловится это глазами через три итерации подгонки. Заданная доля делает
    // пропорцию ДАННЫМИ: голова 0.35 корпуса, пасть 0.40 головы, глаз 0.08 — и разъехаться им нечем.
    // Пусто (0) = размер берётся из `baseSize`, как раньше (корневые места, у которых родителя нет).
    public Vector3 sizeRel;

    // ФОРМА ИЗ ЧУЖОГО ОРГАНА. Место на голове (глаза, нос, уши, ямки) говорит, ЧЕЙ орган его рисует —
    // и это не «адрес визуала» наоборот: орган по-прежнему не знает, куда его рисуют, просто место
    // читает его форму. Отсюда при графте чужого Чутья морда меняется САМА: привил волку пит-орган —
    // мочка сменилась термоямками. Пусто у источника — место рисует свою форму (тварь без Чутья не
    // остаётся безглазой), тот же приём, что у Сердца с грудной клеткой
    public string formFrom;                // имя слота-ИСТОЧНИКА формы (пусто = своя форма места)
    public PartRole formRole;              // какие части источника сюда идут (глаз, ухо, нос, ямка)

    public float linkLength;               // длина звена вдоль хребта, метры
    public float linkTaper;                // сужение ТОЛЬКО ПО ТОЛЩИНЕ (0 = дефолт 1: не сужается).
                                           // Длина при этом НЕ меняется — в этом вся разница с `chainTaper`

    /// <summary>Габарит места для ГРАФА. У цепного места выводится из звена, поэтому `baseSize` и звено
    /// не могут разойтись; у обычного — как задан. Длинная ось у цепи всегда Z: длина > толщины по смыслу.</summary>
    public Vector3 SizeForGraph => linkLength > 0f
                                 ? new Vector3(linkDiameter, linkDiameter, linkLength)
                                 : baseSize;   // цепь: диаметр может быть НЕ ЗАДАН (наследуется от родителя)
}
