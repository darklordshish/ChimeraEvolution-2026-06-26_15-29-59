# -*- coding: utf-8 -*-
"""КЛЕТКА СЛОТА: сечения вдоль оси — форма вида как ТАБЛИЦА ЧИСЕЛ (спека `Docs/models/SPEC-kletka-tela.md`).

Модуль намеренно БЕЗ `bpy`: клетка снимается и проверяется без Blender. Иначе единственный способ
посмотреть на числа — открыть редактор, а это ровно тот путь, которым правка превращается в
подгонку вслепую.

ЗАЧЕМ ТАБЛИЦА, А НЕ ГОТОВЫЙ МЕШ. Модель у нас — форма для ХИМЕРЫ, а химера есть смесь. Две готовые
геометрии смешать нечем; две таблицы одинаковой размерности — покомпонентным средним, вершина к
вершине. Отсюда жёсткое условие: **M и N одинаковы у всех видов для одноимённого слота**.

ОТКУДА БЕРУТСЯ ЧИСЛА. Не из головы: луч щупает ОТЛИВКУ болвана (`volume.py`) — те самые кости и
мышцы, которые сняты с референсов и выверены наложением на фотографию, но превращённые в сплошное
тело. Слои 1 и 2 не выбрасываются, они меняют роль: из геометрии в источник чисел.

ЩУПАТЬ ПРУТЬЯ НАПРЯМУЮ НЕЛЬЗЯ — это стоило шести кругов правок. Скелет с мышцами есть решётка с
пустотами, и «внутри» для луча означает «попал в прут»: диагональ вдоль ребра живёт долго, прямой
бок выходит сразу, сечение выходит ножом. У волка так получилась ширина 0.012 м при высоте 0.364.
"""
import math


# ── РАЗМЕРНОСТИ. Фиксируются ОДИН РАЗ на все виды: разное число станций делает смешение
# невыразимым. Числа выбраны по бюджету (низкополигональный стиль, 20–25 тварей в кадре) и по
# сложности формы: у торса восемь секторов, потому что сечение груди не круглое; у уха четыре,
# потому что ухо плоское и больше нечем описать.
#     СЕРДЦА И ШКУРЫ ЗДЕСЬ НЕТ. `Сердце` — внутреннее место: видно только формой органа, своей
# оболочки у него нет. `Шкура` — свойство покрова, а не отдельное тело. Торс целиком принадлежит
# `хребту` — он корень графа (спека «скелет — орган, а не пустота»).
CAGE = {
    'хребет': (8, 8),    # торс: грудь, поясница, круп
    'шея':    (4, 8),
    'голова': (6, 8),
    'Пасть':  (4, 6),    # ОТДЕЛЬНАЯ оболочка: она открывается, общего кольца с черепом НЕТ
    'Руки':   (6, 6),
    'Ноги':   (7, 6),
    'Хвост':  (5, 6),
    'Чутьё':  (4, 6),    # ухо: конус, а не пластина — на четырёх секторах кольцо есть РОМБ,
                         # и раковина читалась плоской доской с рёбрами по краю
}

# Слоты, у которых деталь парная: мерится ПРАВАЯ, левая получается зеркалом
PAIRED = {'Руки', 'Ноги', 'Чутьё'}

# ── ЧЬЯ ПОВЕРХНОСТЬ. Механический слот и владелец ОБОЛОЧКИ — не одно и то же.
# Рёбра записаны в слот «Сердце», потому что грудная клетка и есть сердце как аугумент. Но клетки у
# «Сердца» нет: место внутреннее, видно только формой органа. А поверхность рёбер — это стенка
# ТОРСА, и владеть ею должен «хребет». Без этой строки луч из грудного позвонка проходил сквозь
# рёбра как сквозь чужое и цеплялся за брюшную стенку в 35 см: сечение груди выходило втрое глубже
# настоящего, и ни одна проверка этого не ловила — число выглядело правдоподобно.
SURFACE_OF = {'Сердце': 'хребет', 'Шкура': 'хребет'}

# ── ПОИМЁННЫЕ ИСКЛЮЧЕНИЯ: пояс конечности рисует КОРПУС, а двигает его конечность.
# У четвероногого лопатка и таз стоят в силуэте ТУЛОВИЩА: плечо и круп — это его линия, а не линия
# ноги. Пока они принадлежали слотам `Руки`/`Ноги`, торс оставался гладкой трубой (на рендере —
# бочка), а в самой конечности их было нечем нарисовать: ось слота шла цепью из ПЯТИ костей с
# резким изломом в поясе, и сечение поперёк излома бессмысленно. Лопатка ушла в корпус — цепь стала
# из четырёх костей, главный излом исчез, и торс вернул себе плечо с крупом. Полигонов ноль.
#     Механика при этом не двигается: слот `Руки` по-прежнему держит лопатку как кость и как риг —
# меняется только ХОЗЯИН ПОВЕРХНОСТИ. Это ровно «обмен работой идёт в обе стороны» из правил.
SURFACE_BONE = {'лопатка': 'хребет', 'подвздошная': 'хребет',
                'седалищная': 'хребет', 'лобковая': 'хребет'}

# ── ЗАМЫКАНИЕ, ПОСЛОТНО. Болван — решётка с дырами: между рёбрами воздух, между пястными костями
# щели. Луч, попавший в дыру, возвращает радиус по случайной кости вместо радиуса по телу. Та же
# операция, что рисует покров (`build.hide`): раздуть на R, потом сжать на R — щели уже R
# затягиваются, а форма толще не становится. В марше это выражается даром: щупать с допуском R и
# вычесть R из результата.
#     ЧИСЛО СВОЁ У КАЖДОГО СЛОТА, и это не педантизм: одним радиусом две работы разного масштаба не
# делаются. Волчьей груди нужно 30 мм (шаг рёбер 37 мм), а морде хватает 5 мм — 30 мм на морде уже
# однажды превратили её в «моську», утроив толщину.
PAD = {'хребет': 0.030, 'шея': 0.018, 'голова': 0.005, 'Пасть': 0.005,
       'Руки': 0.016, 'Ноги': 0.016, 'Хвост': 0.014, 'Чутьё': 0.002}

STEP = 0.002        # шаг марша луча, м — вдвое мельче самой тонкой детали (ухо 10 мм)
REACH = 0.60        # докуда щупать, м


# ── ВЕКТОРНАЯ МЕЛОЧЬ. numpy не тянем: модуль должен считаться и там, где его нет
def _sub(a, b): return (a[0] - b[0], a[1] - b[1], a[2] - b[2])
def _add(a, b): return (a[0] + b[0], a[1] + b[1], a[2] + b[2])
def _mul(a, k): return (a[0] * k, a[1] * k, a[2] * k)
def _dot(a, b): return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]
def _cross(a, b): return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def _norm(a):
    n = math.sqrt(_dot(a, a))
    return (0.0, 1.0, 0.0) if n < 1e-12 else _mul(a, 1.0 / n)


def frames(dirs):
    """Кадры сечений вдоль оси — БЕЗ КРУЧЕНИЯ (параллельный перенос).

    Наивный кадр «сектор 0 вверх от мировой вертикали» разваливается ровно там, где ось сама почти
    вертикальна, — то есть на НОГАХ. Опорное направление там вырождается и перескакивает от станции
    к станции, кольца проворачиваются друг относительно друга, и конечность выходит скрученной
    лентой. Хуже того, портится не только меш: мерили тем же кадром, значит перекручены и числа —
    у одной станции сектор смотрел на переднюю сторону голени, у соседней на боковую.

    Перенос лечит это по построению: кадр задаётся ОДИН РАЗ в начале цепи и дальше едет вдоль оси
    минимальным поворотом. Крутиться ему нечем.

    СРАВНИМОСТЬ МЕЖДУ ВИДАМИ ДЕРЖИТ ЗАТРАВКА, а не мировая ось: правило выбора одно на все виды, а
    цепи слотов анатомически соответственны, поэтому сектор 3 голени волка и сектор 3 голени лося —
    одна и та же сторона ноги. Иначе среднее двух таблиц было бы бессмыслицей."""
    dd = [_norm(d) for d in dirs]
    # ЗАТРАВКА: вверх, а для почти вертикальной оси — вперёд. Порог с запасом, чтобы у ноги не
    # решалось «по случаю»: наклон голени у видов разный, и балансировать на грани нельзя
    ref = (0.0, 1.0, 0.0) if abs(_dot(dd[0], (0.0, 1.0, 0.0))) < 0.80 else (0.0, 0.0, 1.0)
    up = _norm(_sub(ref, _mul(dd[0], _dot(ref, dd[0]))))
    out = []
    for i, d in enumerate(dd):
        if i:
            ax = _cross(dd[i - 1], d)
            s2 = math.sqrt(_dot(ax, ax))
            if s2 > 1e-9:            # повернуть кадр тем же минимальным поворотом, что и ось
                ax = _mul(ax, 1.0 / s2)
                a = math.atan2(s2, _dot(dd[i - 1], d))
                c, sn = math.cos(a), math.sin(a)
                up = _add(_add(_mul(up, c), _mul(_cross(ax, up), sn)),
                          _mul(ax, _dot(ax, up) * (1.0 - c)))
            up = _norm(_sub(up, _mul(d, _dot(up, d))))
        out.append((up, _norm(_cross(d, up))))
    return out


# ── ОБМЕР ПО ОТЛИВКЕ ─────────────────────────────────────────────────────────────────────────────
def measure(slot, axis_bones, placed, vol, m=None, n=None):
    """Снять клетку слота: M станций вдоль оси, N лучей вокруг.

    Ось — ЦЕПЬ КОСТЕЙ слота, а не выдуманная линия. Отсюда, между прочим, исчезает мина И2: длинная
    ось больше не выбирается по максимальной стороне габарита и не может молча переключиться при
    смешении."""
    # numpy и scipy нужны ТОЛЬКО обмеру. Сборка меша по готовой таблице обходится без них — и
    # обязана: у питона внутри Blender их нет, а импорт наверху ронял бы весь генератор.
    import numpy as np
    from .volume import CELL as CELL_M
    if m is None or n is None:
        m, n = CAGE[slot]
    mask = vol.solid(slot, PAD.get(slot, 0.01))
    pts = np.argwhere(mask) * CELL_M + np.array(vol.lo)     # мировые центры своих ячеек

    pts_ax = []
    for name in axis_bones:
        p, r, t = placed[name]
        if not pts_ax:
            pts_ax.append(tuple(p))
        pts_ax.append(tuple(t))
    segs = [(pts_ax[i], pts_ax[i + 1]) for i in range(len(pts_ax) - 1)]
    lens = [math.sqrt(_dot(_sub(b, a), _sub(b, a))) for a, b in segs]
    total = sum(lens)
    if total < 1e-9:
        raise ValueError('нулевая ось у слота %r' % slot)
    half = max(0.5 * total / max(1, m - 1), 0.02)

    # ось считается ВСЯ СРАЗУ: кадр без кручения знать одну станцию не может, ему нужна цепь
    pos_d = []
    for i in range(m):
        u = i / (m - 1.0) if m > 1 else 0.0
        want, acc, seg = u * total, 0.0, 0
        while seg < len(segs) - 1 and acc + lens[seg] < want:
            acc += lens[seg]; seg += 1
        k = 0.0 if lens[seg] < 1e-9 else (want - acc) / lens[seg]
        a, b = segs[seg]
        p = _add(a, _mul(_sub(b, a), k))
        d = _norm(_sub(b, a))

        # СЕРЕДИНА ПЛОТИ, А НЕ ТОЧКА НА КОСТИ. Кость слота не лежит в середине его формы:
        # позвоночник идёт по КРЫШЕ бочки, грудная клетка расширяется книзу, и луч вбок от позвонка
        # отходит от ребра сразу же — цеплял головку в 4 см вместо полуширины в 12. Середина берётся
        # по отливке, поэтому у лапы поправка выходит нулевой сама собой: там кость и есть середина.
        c = p
        if len(pts):
            off = pts - np.array(p)
            sel = np.abs(off @ np.array(d)) <= half
            if sel.any():
                q = pts[sel].mean(0)
                w = q - np.array(p)
                q = np.array(p) + w - np.array(d) * float(w @ np.array(d))   # только ПОПЕРЁК оси
                if vol.at(mask, q):
                    c = tuple(q)

        pos_d.append((u, c, d))

    rows, centers, dirs = [], [], []
    for (u, c, d), (up, side) in zip(pos_d, frames([x[2] for x in pos_d])):
        radii = []
        for j in range(n):
            ang = 2.0 * math.pi * j / n
            radii.append(_march(vol, mask, c, _add(_mul(up, math.cos(ang)), _mul(side, math.sin(ang)))))
        rows.append((round(u, 4), tuple(round(r, 4) for r in radii)))
        centers.append(tuple(round(x, 4) for x in c))
        dirs.append(tuple(round(x, 4) for x in d))
    # ВЫЛЕТ ПЛОТИ ЗА КОНЦЫ ОСИ. Клетка описывает только то, что стоит поперёк станций, — а мясо
    # выходит за крайнюю станцию: грудь идёт вперёд за первый грудной позвонок, круп назад за
    # крестец, морда за конец черепа. Без этих двух чисел торец получается ПЛОСКОЙ СТЕНКОЙ: у волка
    # грудь упиралась в вертикальную плиту, и щель между корпусом и шеей читалась глазом.
    caps = (round(_march(vol, mask, centers[0], _mul(dirs[0], -1.0)), 4),
            round(_march(vol, mask, centers[-1], dirs[-1]), 4))
    # ДОКУДА МОЖНО УТОПИТЬ КОРЕНЬ. Части не сшиваются кольцом, а входят друг в друга, — но глубина
    # входа не может быть числом из головы: у хвоста назад лежит весь круп, а у челюсти назад лежит
    # затылок и кончается через три сантиметра. Меряем по ТЕЛУ ЦЕЛИКОМ и первым выходом наружу:
    # дальше собирать нечего, там воздух.
    body = vol.body()
    d0, step, sink = _norm(_mul(dirs[0], -1.0)), STEP, 0.0
    while sink < REACH and vol.at(body, _add(centers[0], _mul(d0, sink + step))):
        sink += step
    return {'slot': slot, 'm': m, 'n': n, 'length': round(total, 4), 'centers': centers, 'dirs': dirs,
            'caps': caps, 'sink': round(sink, 4),
            'origin': tuple(round(x, 4) for x in pts_ax[0]),
            'tip': tuple(round(x, 4) for x in pts_ax[-1]), 'stations': rows}


def _march(vol, mask, origin, direction, step=STEP, far=REACH):
    """Докуда своя плоть: ПЕРВЫЙ ВЫХОД НАРУЖУ.

    Правило менялось дважды, и оба раза по делу. Пока щупалась решётка из костей, брать приходилось
    ПОСЛЕДНЮЮ точку внутри: полости зверя (грудная, брюшная) пусты, и первый выход возвращал радиус
    по позвонку вместо радиуса по боку. С переходом на отливку полостей не стало — `binary_fill_holes`
    заливает их целиком, — и «последняя точка» превратилась во вред: луч, попавший ВДОЛЬ вытянутой
    детали, бежит по ней и возвращает её длину. У плеча так вышел радиус 0.198 при соседях 0.018 —
    луч ехал вдоль трицепса, и на рендере это была плита."""
    d = _norm(direction)
    last = 0.0
    for i in range(1, int(far / step) + 1):
        if not vol.at(mask, _add(origin, _mul(d, i * step))):
            break
        last = i * step
    return last
