# -*- coding: utf-8 -*-
"""КАДРЫ ПРЕВЬЮ — ОТДЕЛЬНО ОТ СБОРКИ, потому что их читает ещё и детектор.

Детектор кладёт рендер на референс и обязан знать, какой кусок мира попал в кадр. Пока эти числа
жили рядом с `import bpy`, прочитать их он не мог, а держать кадр в двух местах значит однажды
сдвинуть камеру и получить совпадение с натурой, которого нет.

Формат: имя → (позиция камеры, куда смотрит, ширина кадра). Оси BLENDER (Z вверх, зверь в −Y).
Профиль снимается с −X: экранное «вправо» приходится на нос, как на референсной фотографии.
"""

# КАЛИБР, В КОТОРОМ ЗАПИСАНЫ ЧИСЛА НИЖЕ. Кадры снимались на волке, и до второго вида это было
# неотличимо от «просто чисел». Человек в 1.85 в волчий кадр не влезает, поэтому кадр стал ФУНКЦИЕЙ
# калибра: `frame(view, W)` масштабирует всё на W/BASE. У волка W = BASE, и числа выходят те же до
# бита — детектор (`compare.py`), который держит профильный кадр в координатах игры, не ломается.
BASE = 1.170

VIEWS = {
    # имя: (позиция камеры, куда смотрит, размер кадра по большей стороне)
    # ПРОФИЛЬ СНИМАЕТСЯ С −X: камера смотрит в +X, экранное «вправо» приходится на +Z, и зверь
    # оказывается носом вправо — как на референсной фотографии. С другой стороны пришлось бы
    # зеркалить картинку, а зеркаленные сравнения — верный способ однажды принять выдумку за натуру
    'profile': ((-8.0, 0.10, 0.78), (0.0, 0.10, 0.78), 2.30),
    'front':   ((0.0, -8.0, 0.78), (0.0, 0.0, 0.78), 1.30),
    'headfront': ((0.0, -6.0, 1.236), (0.0, 0.0, 1.236), 0.34),
    'head':    ((-3.0, -0.631, 1.236), (0.0, -0.631, 1.236), 0.46),
    'top':     ((0.0, 0.10, 8.0), (0.0, 0.10, 0.0), 2.30),
    # ЧЕРЕП В МАСШТАБЕ ЧЕРЕПА: кадр ровно на голову, чтобы класть на пластину. Правило методики
    # «часть мерится в масштабе части» — у головы десятая доля пикселей профиля, и в общей метрике
    # её ошибки не видны вовсе
    'skull':   ((-3.0, -0.631, 1.236), (0.0, -0.631, 1.236), 0.44),
}


def frame(view, W=BASE, centre=None):
    """Кадр вида в его собственном калибре: (позиция камеры, куда смотрит, размер кадра).

    Масштабируется ВСЁ, включая высоту взгляда: у четвероногого центр тела на 0.67 калибра, у
    двуногого — тоже, потому что калибр у него рост. Это грубо и честно: кадр обязан вместить
    зверя, а не польстить ему. Точная кадровка по габариту — когда появится третий вид и станет
    видно, что общего у их габаритов на самом деле."""
    k = float(W) / BASE
    pos, look, size = VIEWS[view]
    pos = [c * k for c in pos]
    look = [c * k for c in look]
    size = size * k
    if centre is not None:
        # ЦЕЛИТЬСЯ НАДО В СЕРЕДИНУ ГАБАРИТА, А НЕ В ДОЛЮ КАЛИБРА. Доля унаследована от волка: у
        # четвероногого центр тела на 2/3 холки, у двуногого — на половине роста, и человеку кадр
        # срезал ступни. Габарит знает про вид то, чего доля знать не может.
        for i in (1, 2):
            d = centre[i] - look[i]
            look[i] += d
            pos[i] += d
        size = max(size, centre[3] * 1.12)      # запас 12%: зверь не должен упираться в рамку
    return (tuple(pos), tuple(look), size)
