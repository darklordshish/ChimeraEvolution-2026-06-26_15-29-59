# -*- coding: utf-8 -*-
"""ДЕТЕКТОР РАЗМЕРОВ: сверяет модельную линию с ИГРОВЫМИ габаритами.

Зачем отдельный инструмент. Калибр вида (`W`) объявлен «единственным числом, которым вид
пересчитывается целиком», но никто не проверял, что модель этому числу соответствует. Оказалось —
не соответствует: у волка `W = 1.170` (высота в холке по ТЗ), а холка в модели стоит на 0.898 W.
Калибр был подписью под чертежом, а не размером чертежа.

Источник игровых чисел — `Docs/Диаграммы/КАРТА_ТЕЛ.md`, генерируемый детектор: он строит тело
НАСТОЯЩИМ билдером и меряет границы рендереров, поэтому с игрой разойтись не может. Руками числа
сюда не переписываем — парсим файл.

ЧТО С ЧЕМ СРАВНИВАЕТСЯ. Карта меряет мясо (границы деталей), скелет — оси костей. Поэтому кость
раздувается на свой радиус: верх кости = max(y начала, y конца) + max(r0, r1). Это по-прежнему не
покров (шерсти и кожи в клетке нет вовсе, см. `OCENKA-metoda-kletki.md`), так что модель обязана
быть НЕМНОГО МЕНЬШЕ игровой — на проценты, а не на четверть.

ШИРИНУ СВЕРЯТЬ НЕЛЬЗЯ, и это не лень, а свойство меры. В игре она берётся по самому широкому
придатку: у лося это размах рогов (2.307 м при теле в полметра шириной), у человека — разведённые
руки (0.882), у волка — коробки деталей, заведомо толще зверя (0.463 = 0.40 холки, тогда как
настоящий волк 0.20–0.24). Сравнение показывало бы −77% там, где всё верно, и приучало бы листать
красное мимо — ровно то, что запрещено правилом «валидатор, кричащий на намеренное, приучает
игнорировать красное». Ширина остаётся СПРАВОЧНО, без вердикта.

ГЛАВНАЯ ОСЬ У ВИДОВ РАЗНАЯ: у четвероногих и змеи размер задаёт длина, у человека — рост. Вердикт
выносится по ней; вторая ось идёт справочно, её портят рога, иглы и уши.
"""
import io
import os
import re
import sys
import importlib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', errors='replace')

from chimera.skel import from_points   # noqa: E402

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
MAP = os.path.join(REPO, 'Docs', 'Диаграммы', 'КАРТА_ТЕЛ.md')

VIDY = [('Волк', 'wolf', 'д'), ('Человек', 'human', 'в'), ('Лось', 'moose', 'д'),
        ('Ёж', 'hedgehog', 'д'), ('Змея', 'snake', 'д')]
ОСЬ = {'д': 'длина', 'в': 'высота', 'ш': 'ширина'}
ДОПУСК = 0.10        # покров даёт проценты; четверть даёт только неверный калибр или пропорция


def igra():
    """Габариты из карты тел: по каждому виду объединение коробок всех деталей."""
    s = io.open(MAP, encoding='utf-8').read()
    out = {}
    for sec in re.split(r'\n## ', s)[1:]:
        name = sec.split('\n')[0].strip()
        rows = re.findall(r'^\| *[^|]+? *\| *[^|]+? *\| *(-?[\d.]+), *(-?[\d.]+), *(-?[\d.]+) *'
                          r'\| *([\d.]+) *. *([\d.]+) *. *([\d.]+) *\|', sec, re.M)
        if not rows:
            continue
        lo, hi = [1e9] * 3, [-1e9] * 3
        for r in rows:
            c = [float(x) for x in r[:3]]
            g = [float(x) for x in r[3:]]
            for i in range(3):
                lo[i] = min(lo[i], c[i] - g[i] / 2)
                hi[i] = max(hi[i], c[i] + g[i] / 2)
        out[name] = dict(n=len(rows), ш=hi[0] - lo[0], в=hi[1] - lo[1], д=hi[2] - lo[2], низ=lo[1])
    return out


def model(mod):
    """Габариты скелета с учётом толщин костей."""
    sp = importlib.import_module('species.' + mod)
    bones, pl, _ = from_points(sp.DEFS, sp.P, verbose=False)
    by = {b.name: b for b in bones}
    lo, hi = [1e9] * 3, [-1e9] * 3
    for n, (p, _f, t) in pl.items():
        r = max(by[n].r0, by[n].r1)
        for i in range(3):
            lo[i] = min(lo[i], min(p[i], t[i]) - r)
            hi[i] = max(hi[i], max(p[i], t[i]) + r)
    return sp, pl, by, lo, hi


def верх(pl, by, n):
    p, _f, t = pl[n]
    return max(p[1], t[1]) + max(by[n].r0, by[n].r1)


def отчёт():
    g = igra()
    print('# РАЗМЕРЫ: модельная линия против игры')
    print()
    print('Отчёт СГЕНЕРИРОВАН `Tools/Blender/razmer.py`, руками не править. Игровые числа — из')
    print('`Docs/Диаграммы/КАРТА_ТЕЛ.md`, модельные — габарит скелета с толщинами костей.')
    print('Модель обязана быть чуть меньше игровой: покрова в клетке нет.')
    print()
    print('| вид | калибр W | ГЛАВНАЯ ОСЬ: модель / игра | вторая ось | ширина (справочно) |')
    print('|---|---|---|---|---|')
    беды = []
    for имя, mod, ось in VIDY:
        sp, pl, by, lo, hi = model(mod)
        м = dict(д=hi[2] - lo[2], в=hi[1] - lo[1], ш=hi[0] - lo[0])
        и = g[имя]
        вт = 'в' if ось == 'д' else 'д'

        def кл(k):
            return '%s %.3f / %.3f · %+.0f%%' % (ОСЬ[k], м[k], и[k], (м[k] / и[k] - 1) * 100)
        d = м[ось] / и[ось] - 1
        знак = 'OK' if abs(d) <= ДОПУСК else 'НЕТ'
        if abs(d) > ДОПУСК:
            беды.append((имя, ось, м[ось], и[ось], sp.W))
        print('| %s | %.3f | %s · %s | %s | %.3f / %.3f |'
              % (имя, sp.W, знак, кл(ось), кл(вт), м['ш'], и['ш']))
    print()
    if беды:
        print('**Главная ось расходится больше чем на %d%%:**' % (ДОПУСК * 100))
        print()
        for имя, k, a, b, W in беды:
            print('- **%s**, %s: модель %.3f при игровых %.3f (%+.0f%%). Если дело ТОЛЬКО в'
                  ' масштабе, калибр должен быть **W = %.3f** вместо %.3f.'
                  % (имя, ОСЬ[k], a, b, (a / b - 1) * 100, W * b / a, W))
    else:
        print('Все виды в допуске %d%% по главной оси.' % (ДОПУСК * 100))


ОРИЕНТИРЫ = {   # вид → [(мера, кость, доля калибра по ТЗ)] из `Docs/models/species/<вид>.md`
    'wolf': [('холка', 'холка', 1.000), ('затылок', 'затылочный', 1.195),
             ('нос', 'череп', 1.010), ('крестец', 'крестец', 0.979)],
}


def ориентиры():
    for mod, спис in ОРИЕНТИРЫ.items():
        sp, pl, by, lo, hi = model(mod)
        print()
        print('## Ориентиры по ТЗ: %s (W = %.3f)' % (mod, sp.W))
        print()
        print('| мера | ТЗ | модель | расхождение |')
        print('|---|---|---|---|')
        for что, кость, норма in спис:
            v = (верх(pl, by, кость) - lo[1]) / sp.W
            print('| %s | %.3f W | %.3f W | %+.0f%% |' % (что, норма, v, (v / норма - 1) * 100))


if __name__ == '__main__':
    отчёт()
    ориентиры()
