"""ПАНЕЛИ Б, ИТЕРАЦИЯ 7 (05.11, замечания геймдизайнера и ГеймБосса к Б6 в игре, поверх `b6-paneli.json`). Полоса грудины одной плоскостью: без перепада на оси, в позе удара он читался тёмным клином. Надколенник одной плоскостью, наклон вверх: верх глубже, низ вперёд, поэтому верхний свет делает его светлым.

  python b7_paneli.py b6-paneli.json выход.json
"""
import sys, json

P = json.load(open(sys.argv[1], encoding='utf-8')); by = {p['imya']: p for p in P}
for t in by['грудь']['tochki']:
    if t[0] <= 0.03 and 1.31 < t[1] < 1.51: t[2] = 0.003
for t in by['низ перед']['tochki']:
    if t[:2] == [0.138, 0.575]: t[2] = 0.001
    if t[:2] == [0.14, 0.49]: t[2] = 0.008
    if t[:2] in ([0.172, 0.535], [0.105, 0.535]): t[2] = 0.0045
json.dump(P, open(sys.argv[2], 'w', encoding='utf-8'), ensure_ascii=False, indent=0)
