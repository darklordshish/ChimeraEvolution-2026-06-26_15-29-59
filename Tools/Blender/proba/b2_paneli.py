"""ПАНЕЛИ Б, ИТЕРАЦИЯ 2 (05.11, по замечаниям критика, проверенным срезами): правки поверх `b-paneli.json`, точки и глубина заданы рукой числом. Ключица и яремная ямка, полоса грудины только до низа грудины, дельта с точкой схождения ниже и задняя панель, край широчайшей у подмышки, подреберье, ягодица с нижней границей.

  python b2_paneli.py b-paneli.json выход.json
"""
import sys, json

P = json.load(open(sys.argv[1], encoding='utf-8')); by = {p['imya']: p for p in P}


def zam(p, ubrat, novye, rebra):
    st = {i: j for j, i in enumerate(i for i, t in enumerate(p['tochki']) if not ubrat(t))}
    p['tochki'] = [t for t in p['tochki'] if not ubrat(t)]; p['rebra'] = [[st[a], st[b]] for a, b in p['rebra'] if a in st and b in st]
    n0 = len(p['tochki']); p['tochki'] += novye; p['rebra'] += [[a + n0, b + n0] for a, b in rebra]


# 1. шея и ключица: яма, длинная плоскость ключицы к акромиону, уклон трапеции выше; 4. дельта: схождение ниже (z 1.40 вместо 1.44), верхний угол срезан
g = by['грудь']; g['z'][1] = 1.62
zam(g, lambda t: t[1] > 1.47 or (t[0] > 0.19 and t[1] > 1.27),
    [[0, 1.525, -0.007], [0.024, 1.535, 0.003], [0.10, 1.517, 0.007], [0.19, 1.505, 0.004], [0.10, 1.47, -0.006], [0.05, 1.585, 0.0], [0.115, 1.55, -0.002],
     [0.215, 1.47, 0.003], [0.24, 1.40, 0.007], [0.205, 1.34, -0.002], [0.255, 1.31, 0.0]],
    [[0, 1], [1, 2], [2, 3], [1, 5], [5, 6], [6, 3], [3, 7], [7, 8], [8, 9], [8, 10]])
# ключица полосой: нижний край идёт параллельно верхнему, а не плитой от шеи
n_ = len(g['tochki']); g['tochki'] += [[0.024, 1.505, -0.001], [0.10, 1.494, 0.002], [0.19, 1.482, -0.002]]; g['rebra'] += [[n_, n_ + 1], [n_ + 1, n_ + 2]]
# 2. молния: ось ниже грудины без глубокой борозды и без цепи ограничений
for t in g['tochki']:
    if t[0] == 0 and t[1] < 1.3: t[2] = -0.002
axis = {i for i, t in enumerate(g['tochki']) if t[0] == 0 and t[1] < 1.3}
g['rebra'] = [e for e in g['rebra'] if not (e[0] in axis and e[1] in axis)]
for t in g['tochki']:
    if 0 < t[0] < 0.04 and 1.34 < t[1] < 1.47: t[2] = -0.001
    if t[0] == 0 and 1.3 < t[1] < 1.47: t[2] = -0.001
# 7. подреберье: край клетки выступает над животом
for t in g['tochki']:
    if 0.06 < t[0] < 0.15 and 1.2 < t[1] < 1.3: t[2] = 0.006
# 4. задняя панель дельты; 5. подмышка: панель спины шире, край широчайшей вынесен, диагональ вдоль неё
b = by['спина']; b['x_max'] = 0.185; b['ruki_z'] = 1.36   # ниже рука висит рядом: в проекции панель складывается, грань выворачивается
for t in b['tochki']:
    if t[:2] == [0.155, 1.285]: t[2] = 0.006
    if t[:2] == [0.135, 1.335]: t[2] = 0.005
    if t[:2] == [0.15, 1.37]: t[2] = 0.003
    if t[:2] == [0.115, 1.23]: t[2] = 0.004
P.append(dict(imya='дельта зад', vid='back', x_min=0.2, x_max=0.31, z=[1.33, 1.52], konech=1, ruki=1, ruki_z=1.33, tochki=[[0.24, 1.40, 0.006], [0.215, 1.47, 0.002]], rebra=[[0, 1]]))
# 7. ягодица одной гранью с ясной нижней границей
s = by['низ сзади']
for t in s['tochki']:
    if t[:2] == [0.11, 0.93]: t[2] = 0.015
    if t[:2] == [0.035, 0.82]: t[2] = -0.008
    if t[:2] == [0.12, 0.795]: t[2] = -0.006
json.dump(P, open(sys.argv[2], 'w', encoding='utf-8'), ensure_ascii=False, indent=0)
