"""ПАНЕЛИ Б, ИТЕРАЦИЯ 3 (05.11): цепи рёбер по границам крупных масс поверх `b2-paneli.json`. Торс — по `огранка-рёбра.png` (граф уже там), ноги — по массам `вид.png`, точки заданы рукой. Лацкан делится ямкой и ключицами, шов грудины заканчивается на её конце, клетка и таз разделены подреберьем и гребнем. Плоскостность внутри панели задаёт `--plan` в `ogranka_telo.py`.

  python b3_paneli.py b2-paneli.json выход.json
"""
import sys, json

P = json.load(open(sys.argv[1], encoding='utf-8')); by = {p['imya']: p for p in P}


def dob(p, novye, rebra):
    """новые точки и рёбра; индекс ≥ 1000 — новая точка, иначе имеющаяся"""
    n = len(p['tochki']); p['tochki'] += novye; p['rebra'] += [[(a - 1000 + n) if a >= 1000 else a, (b - 1000 + n) if b >= 1000 else b] for a, b in rebra]


def ix(p, x, z):
    return min(range(len(p['tochki'])), key=lambda i: (p['tochki'][i][0] - x) ** 2 + (p['tochki'][i][1] - z) ** 2)


g = by['грудь']
# шов грудины: приподнятая полоса, заканчивается острием; ямка только у верха
for t in g['tochki']:
    if t[0] == 0 and 1.34 < t[1] < 1.47: t[2] = 0.004
    if 0 < t[0] < 0.03 and 1.34 < t[1] < 1.51: t[2] = 0.003
    if t[0] == 0 and 1.30 < t[1] <= 1.34: t[2] = 0.002
g['rebra'].append([ix(g, 0.024, 1.345), ix(g, 0, 1.315)])
# лацкан: плита шея–грудина разбита на шею и трапецию, ключица замыкает снизу
dob(g, [[0.03, 1.56, -0.004], [0.085, 1.53, 0.0]], [[ix(g, 0.05, 1.585), 1000], [1000, ix(g, 0.024, 1.535)], [1000, 1001], [1001, ix(g, 0.10, 1.517)], [1001, ix(g, 0.115, 1.55)]])
# клетка и таз: край клетки вперёд и наружу, талия внутрь, живот ниже клетки
for t in g['tochki']:
    if 0.06 < t[0] < 0.15 and 1.2 < t[1] < 1.3: t[2] = 0.008
    if t[:2] == [0.055, 1.15]: t[2] = 0.0
    if t[:2] == [0.095, 1.14]: t[2] = -0.007
    if t[:2] == [0.055, 1.09]: t[2] = 0.002
g['rebra'].append([ix(g, 0.075, 1.25), ix(g, 0.115, 1.185)])
# спина: поясница и край широчайшей замкнуты, V держится
b = by['спина']
b['rebra'] += [[ix(b, 0.095, 1.11), ix(b, 0.045, 1.08)], [ix(b, 0.035, 1.18), ix(b, 0.115, 1.23)], [ix(b, 0.045, 1.08), ix(b, 0, 1.075)]]
# бедро и голень спереди: три длинные плиты, надколенник плоскостью
n = by['низ перед']
dob(n, [[0.075, 0.72, 0.001], [0.082, 0.60, 0.001], [0.165, 0.72, 0.001], [0.178, 0.60, 0.001], [0.125, 0.42, 0.002], [0.20, 0.40, 0.003], [0.19, 0.27, 0.002]],
    [[1000, 1001], [1001, ix(n, 0.105, 0.535)], [1002, 1003], [1003, ix(n, 0.172, 0.535)], [ix(n, 0.14, 0.49), 1004], [ix(n, 0.14, 0.49), 1005], [1005, 1006]])
# бедро и икра сзади: граница ягодицы, икра двумя вершинами на разной высоте
s = by['низ сзади']
for t in s['tochki']:
    if t[:2] == [0.14, 0.40]: t[2] = 0.009
    if t[:2] == [0.15, 0.30]: t[2] = 0.003
dob(s, [[0.17, 0.36, 0.010], [0.112, 0.60, 0.002], [0.165, 0.62, 0.002]],
    [[1001, ix(s, 0.135, 0.50)], [1002, ix(s, 0.135, 0.50)], [ix(s, 0.14, 0.40), 1000], [1000, ix(s, 0.17, 0.17)]])
json.dump(P, open(sys.argv[2], 'w', encoding='utf-8'), ensure_ascii=False, indent=0)
