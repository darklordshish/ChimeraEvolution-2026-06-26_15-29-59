"""ПАНЕЛИ Б, ИТЕРАЦИЯ 5 (05.11, точечные правки к Б4). Спина: край широчайшей косо от подмышки к оси на z 1.17 вместо поперечной ленты. Шаг: без горизонтальной кромки. Бедро: без внутренней цепи. Нога: икра 6 мм, выпуклости на разной высоте, надколенник одной плоскостью. Грудь: нижний край плиты мельче, клин у конца грудины слабее.

  python b5_paneli.py b4-paneli.json выход.json
"""
import sys, json

P = json.load(open(sys.argv[1], encoding='utf-8')); by = {p['imya']: p for p in P}


def ubrat(p, f):
    st = {i: j for j, i in enumerate(i for i, t in enumerate(p['tochki']) if not f(t))}
    p['tochki'] = [t for t in p['tochki'] if not f(t)]; p['rebra'] = [[st[a], st[b]] for a, b in p['rebra'] if a in st and b in st]


def ix(p, x, z): return min(range(len(p['tochki'])), key=lambda i: (p['tochki'][i][0] - x) ** 2 + (p['tochki'][i][1] - z) ** 2)
def dob(p, novye, rebra):
    n = len(p['tochki']); p['tochki'] += novye; p['rebra'] += [[(a - 1000 + n) if a >= 1000 else a, (b - 1000 + n) if b >= 1000 else b] for a, b in rebra]


# 1. спина
b = by['спина']
ubrat(b, lambda t: t[:2] in ([0, 1.3], [0.095, 1.3], [0.115, 1.23], [0.135, 1.335], [0.155, 1.285], [0.125, 1.27]))
dob(b, [[0.145, 1.315, 0.002], [0.105, 1.268, 0.002], [0.06, 1.225, 0.001], [0.09, 1.35, 0.004]],
    [[1000, 1001], [1001, 1002], [1002, ix(b, 0, 1.17)], [ix(b, 0.06, 1.45), 1003], [1003, 1001], [ix(b, 0.15, 1.37), 1000], [ix(b, 0.115, 1.455), 1003]])
dob(b, [[0.135, 1.262, 0.001]], [[ix(b, 0.145, 1.315), 1000], [1000, ix(b, 0.095, 1.11)]])   # широчайшая под косой линией: плита смотрит назад, а не вниз
for t in b['tochki']:
    if t[:2] == [0.15, 1.37]: t[2] = 0.002
# 2. шаг: кромки нет, складка уходит в бедро
n = by['низ перед']
ubrat(n, lambda t: t[:2] in ([0.06, 0.885], [0.075, 0.72], [0.082, 0.6]))
n['rebra'].append([ix(n, 0.045, 0.915), ix(n, 0.07, 0.74)])
# 4. надколенник одной плоскостью, выпуклости на разной высоте
for t in n['tochki']:
    if t[:2] in ([0.138, 0.575], [0.14, 0.49], [0.172, 0.535], [0.105, 0.535]): t[2] = 0.004
    if t[:2] == [0.125, 0.62]: t[2] = 0.003
    if t[:2] == [0.2, 0.4]: t[1] = 0.37
s = by['низ сзади']
for t in s['tochki']:
    if t[:2] in ([0.14, 0.4], [0.17, 0.36]): t[2] = 0.006
dob(s, [[0.115, 0.43, 0.004]], [[ix(s, 0.135, 0.5), 1000], [1000, ix(s, 0.15, 0.3)]])
# 5. клин у конца грудины
g = by['грудь']
for t in g['tochki']:
    if 0.04 < t[0] < 0.16 and 1.31 < t[1] < 1.40 and t[2] > 0.008: t[2] = 0.006
    if t[:2] == [0, 1.315]: t[2] = 0.003
# пятно на широчайшей: плита под косой линией шла прямо к боку и смотрела вниз; вершина на массе широчайшей разворачивает её назад
dob(b, [[0.095, 1.205, 0.003]], [[ix(b, 0.06, 1.225), 1000], [1000, ix(b, 0.095, 1.11)]])
json.dump(P, open(sys.argv[2], 'w', encoding='utf-8'), ensure_ascii=False, indent=0)
