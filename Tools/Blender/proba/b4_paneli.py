"""ПАНЕЛИ Б, ИТЕРАЦИЯ 4 (05.11, по замечаниям к Б3). Поверх `b3-paneli.json`: поясница снова простой клин, ягодица одной гранью с нижней границей, голень и колено без выноса, по плоскости на ключицу, клин от шеи обрывается в яремной ямке, край под грудью поднят к подмышке. Живот и ягодица меняют контур профиля до 1 см (разрешено).

  python b4_paneli.py b3-paneli.json выход.json
"""
import sys, json

P = json.load(open(sys.argv[1], encoding='utf-8')); by = {p['imya']: p for p in P}


def ix(p, x, z): return min(range(len(p['tochki'])), key=lambda i: (p['tochki'][i][0] - x) ** 2 + (p['tochki'][i][1] - z) ** 2)
def ubrat(p, f):
    st = {i: j for j, i in enumerate(i for i, t in enumerate(p['tochki']) if not f(t))}
    p['tochki'] = [t for t in p['tochki'] if not f(t)]; p['rebra'] = [[st[a], st[b]] for a, b in p['rebra'] if a in st and b in st]


# 1. поясница: клин спины без узких шипов
b = by['спина']; ubrat(b, lambda t: t[:2] in ([0.035, 1.18], [0.045, 1.08]))
for t in b['tochki']:
    if t[0] == 0 and t[1] < 1.2: t[2] = -0.003
# 1. ягодица одной гранью, нижняя граница, профиль до 1 см
s = by['низ сзади']; ubrat(s, lambda t: t[:2] == [0.12, 0.795] and False)
for t in s['tochki']:
    if t[:2] == [0.11, 0.93]: t[2] = 0.010
    if t[:2] == [0.035, 0.82]: t[2] = -0.010
    if t[:2] == [0.12, 0.795]: t[2] = -0.010
    if t[:2] == [0, 1.0]: t[2] = -0.006
# 2. голень и колено: вынос икры меньше, ямка мельче
for t in s['tochki']:
    if t[:2] == [0.14, 0.40]: t[2] = 0.004
    if t[:2] == [0.15, 0.30]: t[2] = 0.002
    if t[:2] == [0.17, 0.36]: t[2] = 0.004
    if t[:2] == [0.135, 0.50]: t[2] = 0.0
n = by['низ перед']
for t in n['tochki']:
    if t[:2] == [0.138, 0.575]: t[2] = 0.005
    if t[:2] == [0.14, 0.49]: t[2] = 0.005
    if t[:2] in ([0.172, 0.535], [0.105, 0.535]): t[2] = 0.0
    if t[:2] == [0.155, 0.35]: t[2] = 0.002
    if t[:2] == [0.055, 1.0] or t[:2] == [0.055, 0.97]: t[2] = 0.004
    if t[:2] == [0, 0.945]: t[2] = -0.006
for k in ('низ перед', 'низ сзади'): by[k]['ny'] = 0.5
# 3. ключицы и галстук
g = by['грудь']
ubrat(g, lambda t: t[:2] in ([0.024, 1.535], [0.085, 1.53]))
i0 = ix(g, 0, 1.525); ic = ix(g, 0.10, 1.517); ik = ix(g, 0.024, 1.505); ish = ix(g, 0.03, 1.56); ibs = ix(g, 0.05, 1.585)
g['rebra'] += [[i0, ic], [i0, ik], [ish, i0], [ibs, ish]]
for t in g['tochki']:
    if t[:2] == [0.03, 1.56]: t[2] = -0.006
    if t[:2] == [0, 1.525]: t[2] = -0.009
    if t[:2] == [0.10, 1.517]: t[2] = 0.006
    if t[:2] == [0.10, 1.494]: t[2] = 0.004
    # край под грудью к подмышке
    if 0.11 < t[0] < 0.175 and 1.33 < t[1] < 1.375: t[1] = round(t[1] + 0.03 * (t[0] - 0.09) / 0.08, 4)
# поправка после кадра: полоса на спине от перепада оси, шарнир над коленом
for t in b['tochki']:
    if t[0] == 0 and 1.2 < t[1] < 1.5: t[2] = -0.005
    if t[0] == 0 and t[1] < 1.2: t[2] = -0.004
for t in n['tochki']:
    if t[:2] == [0.14, 0.49]: t[2] = 0.002
    if t[:2] == [0.138, 0.575]: t[2] = 0.003
    if t[:2] == [0.155, 0.35]: t[2] = 0.001
# клин спины: край широчайшей сходится к оси, а не идёт поперёк
b['rebra'] += [[ix(b, 0.115, 1.23), ix(b, 0, 1.17)]]
b['rebra'] = [e for e in b['rebra'] if not (e[0] in (ix(b, 0, 1.30),) or e[1] in (ix(b, 0, 1.30),))]
json.dump(P, open(sys.argv[2], 'w', encoding='utf-8'), ensure_ascii=False, indent=0)
