# -*- coding: utf-8 -*-
"""ОБОЛОЧКА ЧЕРЕПА ЧЕЛОВЕКА — ЭЛЛИПСОИД ПО ТРЁМ ПРОМЕРАМ, а не обвод с пластины. И это оговорка,
а не описание метода: у остальных видов профиль СНИМАЕТСЯ попиксельно (`skullprofile.py`), здесь
снимать не с чего.

ПОЧЕМУ НЕ С ПЛАСТИНЫ. Прежний `human_skull_data.py` в шапке ссылался на
`ref/skeleton/human_skull_lateral.jpg` и заявлял «глубины Z проверены антропометрией: высота свода
0.135 м». Оба утверждения неверны:
  · картинка — ОБЛОМОК СВОДА под углом, без лица и без челюсти; ни одного из заявленных промеров
    с неё снять нельзя;
  · в самих данных высота свода выходила 0.0954 м, а не 0.135 — то есть паспорт расходился с
    содержимым файла;
  · скрипт-генератор `skullprofile_human.py`, на который файл ссылался, в репозитории отсутствует.
Второй референс, `human_skeleton_side_vesalius_REFERENCE.jpg`, даёт голову строго в профиль, но
лицо и челюсть закрыты кистью скелета, а гравюра штрихована — порог заливает весь кроп (проверено).

ЧТО ВЗЯТО ВМЕСТО. Три табличных промера головы взрослого человека, в долях роста — тот же источник,
которым в `human.py` уже заданы `SKULL_LEN` и точка вертекса:
    высота головы (вертекс → подбородок) 0.133 роста · длина 0.105 · ширина 0.082
Голова близка к эллипсоиду, лицо добавляют отдельные кости (скула, челюсть), поэтому эллипсоид
здесь — не упрощение формы, а описание МОЗГОВОГО ЧЕРЕПА, чем оболочка и была всегда.

ОСЬ ИДЁТ ОТ ОСНОВАНИЯ К ВЕРТЕКСУ, а не вперёд к лицу. Прежняя ось была копией волчьей — от мыщелка
к резцам, — и у человека это давало голову, лежащую под 25° к горизонту: темя вставало на 1.768
при росте 1.850, голова читалась в 0.176 м вместо 0.246. Обе точки правильной оси в `human.py`
лежали и лежат (`череп_низ`, `череп_верх`), их же использует общий граф; кость просто брала не ту пару.

Запуск:  python skullhuman.py
"""
import io
import math
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', errors='replace')
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'species', 'human_skull_data.py')

M = 25                     # станций вдоль оси — столько же, сколько было
ЦЕНТР = 0.42               # где эллипсоид всего толще, в долях оси (теменные бугры)
ПОЛУ = 0.57                # полуось эллипсоида вдоль оси: t от -0.18 до 1.02
# Доли ДЛИНЫ ОСИ (ось = основание черепа → вертекс). Ось поднимается вперёд-вверх под 60°,
# поэтому «вперёд» и «назад» здесь — перпендикуляр к ней, а не горизонталь
ВПЕРЁД = 0.55              # от оси к лобно-лицевой стороне
НАЗАД = 0.33               # от оси к затылку: затылок выступает меньше, чем лоб
ШИРИНА = 0.40              # полуширина в самом широком месте


def s(t):
    """Эллиптический сбег: 1 в середине, 0 на концах."""
    v = 1.0 - ((t - ЦЕНТР) / ПОЛУ) ** 2
    return math.sqrt(max(0.0, v))


ГОЛОВА = """# -*- coding: utf-8 -*-
\"\"\"СЕЧЕНИЯ ЧЕРЕПА ЧЕЛОВЕКА — ЭЛЛИПСОИД ПО ТРЁМ ПРОМЕРАМ, НЕ ОБВОД С ПЛАСТИНЫ.

Сгенерировано `Tools/Blender/skullhuman.py` — РУКАМИ НЕ ПРАВИТЬ, правка потеряется при следующем
прогоне. Почему здесь эллипсоид, а у прочих видов обвод, и чем был неверен прежний файл —
в шапке генератора. Коротко: пригодной боковой пластины черепа человека в референсах НЕТ, а
прежний файл ссылался на обломок свода под углом и заявлял высоту свода 0.135 м при 0.0954 в
собственных данных.

Формат станции: (t, верх, низ, полуширина) — ТОЛЬКО МОЗГОВОЙ ЧЕРЕП, нижняя челюсть отдельной
костью. Все величины — В ДОЛЯХ ДЛИНЫ ОСИ, метров в данных нет.

ОСЬ — ОСНОВАНИЕ ЧЕРЕПА → ВЕРТЕКС (`череп_низ` → `череп_верх` в `human.py`), а не мыщелок → резцы,
как у четвероногих: у человека длинная ось головы вертикальна. `верх` смотрит ВПЕРЁД (лоб и лицо),
`низ` — НАЗАД (затылок).\"\"\"

# Концы оси задаются ТОЧКАМИ вида, а не пикселями: пластины нет, переводить не с чего
AXIS = ('череп_низ', 'череп_верх')

# Скуловая дуга ИСКЛЮЧЕНА из ширины и строится отдельной костью
ARCH = (0.0350, 0.42, 0.28, 0.68)

STATIONS = [
"""

with io.open(OUT, 'w', encoding='utf-8') as f:
    f.write(ГОЛОВА)
    for i in range(M):
        t = i / (M - 1.0)
        k = s(t)
        f.write('    (%.4f, %.4f, %.4f, %.4f),\n'
                % (t, ВПЕРЁД * k, -НАЗАД * k, ШИРИНА * k))
    f.write(']\n')

print('записано: %s' % OUT)
print('при оси L: толщина профиля %.3f L · ширина %.3f L' % (ВПЕРЁД + НАЗАД, 2 * ШИРИНА))
