def кольца(c, слот):
    """Вершины клетки без Blender — тем же построением, что и `seams.py`."""
    out = []
    for (u, rad), ctr, (up, side) in zip(c['stations'], c['centers'], cg.frames(c['dirs'])):
        for j, r in enumerate(rad):
            a = 2.0 * math.pi * j / c['n']
            d = [up[k] * math.cos(a) + side[k] * math.sin(a) for k in range(3)]
            out.append(tuple(ctr[k] + d[k] * r for k in range(3)))
    if слот in cg.PAIRED:
        out += [(-x, y, z) for x, y, z in out]
    return out


def мера(mod):
    sp = importlib.import_module('species.' + mod)
    cages = importlib.import_module('species.%s_cage' % mod).CAGES
    V = {s: кольца(cages[s], s) for s in cages}
    все = [v for s in V for v in V[s]]
    W = sp.W
    земля = min(v[1] for v in все)

    def верх(s):
        return (max(v[1] for v in V[s]) - земля) / W

    def низ(s):
        return (min(v[1] for v in V[s]) - земля) / W

    def впер(s):
        return max(v[2] for v in V[s])

    def взад(s):
        return min(v[2] for v in V[s])

    м = {}
    if 'голова' in V:
        м['темя'] = верх('голова')
        м['длина головы'] = (впер('голова') - взад('голова')) / W
        м['нос, высота'] = max(v[1] for v in V['голова'] if v[2] > впер('голова') - 0.02 * W)
        м['нос, высота'] = (м['нос, высота'] - земля) / W
    if 'голова' in V:
        низголовы = низ('Пасть') if 'Пасть' in V else низ('голова')
        м['высота головы'] = верх('голова') - низголовы
    if 'шея' in V:
        м['основание шеи'] = верх('шея')
    if 'хребет' in V:
        м['холка'] = верх('хребет')
        м['низ груди'] = низ('хребет')
    if 'Сердце' in V:
        м['низ груди'] = min(м.get('низ груди', 9), низ('Сердце'))
    if 'Хвост' in V:
        м['длина хвоста'] = max(math.dist(a, b) for a in V['Хвост'] for b in V['Хвост']) / W
        м['нос→корень хвоста'] = (впер('голова') - впер('Хвост')) / W
    return sp, м


