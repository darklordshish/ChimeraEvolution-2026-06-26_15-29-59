def линия(pts, z):
    """Интерполяция ломаной, заданной парами (z, y); вне диапазона — None."""
    p = sorted(pts)
    if z < p[0][0] or z > p[-1][0]:
        return None
    for (z0, y0), (z1, y1) in zip(p, p[1:]):
        if z0 <= z <= z1:
            k = 0.0 if z1 == z0 else (z - z0) / (z1 - z0)
            return y0 + (y1 - y0) * k
    return None


def огибающие(cages, слоты):
    """Верхняя и нижняя линии тела как ЛОМАНЫЕ ПО СТАНЦИЯМ, а не по попаданию вершин в срез.

    Клетка — это M×N вершин, и между станциями вершин НЕТ: у шеи волка их четыре на полметра, то
    есть одна на 12 см. Замер «взять всё, что попало в срез толщиной 4 см» между станциями находил
    пустоту и показывал провал верха на 26 см там, где поверхность непрерывна. Огибающая по
    станциям такого артефакта не даёт: каждая станция — точка ломаной, между ними линия."""
    # ОГИБАЮЩАЯ СЧИТАЕТСЯ ПО СЛОТАМ ОТДЕЛЬНО, А ПОТОМ БЕРЁТСЯ МАКСИМУМ. Свалить станции всех
    # слотов в один список и отсортировать по z нельзя: у головы и у пасти станции стоят на
    # близких z, но на разной высоте, ломаная получается пилой, и интерполяция между зубьями даёт
    # число, которого на теле нет. Так шея показывала толщину 39 мм при настоящих ~200
    верх, низ = {}, {}
    for слот in слоты:
        c = cages[слот]
        ring = сечения(c, слот)
        верх[слот], низ[слот] = [], []
        for ctr, vs, пусто in ring:
            # СТАНЦИЯ С НУЛЕВЫМИ РАДИУСАМИ — НЕ ПОВЕРХНОСТЬ, А ТОЧКА. Клетка сама пишет, что на
            # корневой станции слота плоть принадлежит родителю и её закрывает общее кольцо соседа
            # при сборке. Для огибающей такая станция ядовита: она стягивает верх и низ в одну
            # точку, и шея показывала толщину 10 мм там, где она нормальная
            if пусто:
                continue
            верх[слот].append((ctr[2], max(v[1] for v in vs)))
            низ[слот].append((ctr[2], min(v[1] for v in vs)))
    return верх, низ


def сечения(c, слот):
    """То же построение, что в `silhouette.кольца`, но кольца НЕ СВАЛЕНЫ В КУЧУ — по станциям."""
    out = []
    for (u, rad), ctr, (up, side) in zip(c['stations'], c['centers'], cg.frames(c['dirs'])):
        vs = []
        for j, r in enumerate(rad):
            a = 2.0 * math.pi * j / c['n']
            d = [up[k] * math.cos(a) + side[k] * math.sin(a) for k in range(3)]
            vs.append(tuple(ctr[k] + d[k] * r for k in range(3)))
        if слот in cg.PAIRED:
            vs += [(-x, y, z) for x, y, z in vs]
        out.append((ctr, vs, max(rad) <= 1e-6))
    return out


def свести(mod):
    sp = importlib.import_module('species.' + mod)
    cages = importlib.import_module('species.%s_cage' % mod).CAGES
    V = {s: sil.кольца(cages[s], s) for s in cages}
    # ЗЕМЛЯ И НОС — ПО ВСЕМУ ТЕЛУ, а контур — ПО КОРПУСУ. Эталонный обвод ведёт линию по спине и
    # брюху («корень хвоста → круп → спина → холка → загривок → затылок → лоб → нос» и обратно по
    # низу); ног и ушей в нём нет вовсе. Если их не убрать, «низ» в середине зверя окажется на
    # земле — это будет лапа, а не брюхо, и детектор покажет полметра расхождения на здоровом месте
    все = [v for s in V for v in V[s]]
    земля = min(v[1] for v in все)
    нос = max(v[2] for v in все)
    корпус = [v for s in V if s not in ('Руки', 'Ноги', 'Чутьё') for v in V[s]]
    E = эталон(mod)
    # эталон: (z, y) в метрах, земля уже на нуле по построению `to_model`
    ET = [(z, y) for z, y in E['TOP']]
    EB = [(z, y) for z, y in E['BOT']]
    сдвиг = нос - max(z for z, _ in ET)      # совмещение по кончику носа
    ET = [(z + сдвиг, y) for z, y in ET]
    EB = [(z + сдвиг, y) for z, y in EB]
    СЛОТЫ = [x for x in cages if x not in ('Руки', 'Ноги', 'Чутьё')]
    МВ, МН = огибающие(cages, СЛОТЫ)
    return sp, (МВ, МН), земля, ET, EB


if __name__ == '__main__':
    mod = sys.argv[1] if len(sys.argv) > 1 else 'wolf'
    sp, (МВ, МН), земля, ET, EB = свести(mod)
    W = sp.W
    вседz = [z for k in МВ for z, _ in МВ[k]]
    z0 = max(min(z for z, _ in ET), min(вседz))
    z1 = min(max(z for z, _ in ET), max(вседz))
    print('# КОНТУР ПРОТИВ ЭТАЛОНА — %s (W = %.3f)' % (mod, W))
    print()
    print('Совмещено по земле и кончику носа. Плюс — модель ВЫШЕ эталона по верху / НИЖЕ по низу,')
    print('то есть толще; минус — тоньше. Отсчёт z от носа назад, в долях калибра.')
    print()
    print('| от носа | верх: модель / эталон | низ: модель / эталон | толщина м/э |')
    print('|---|---|---|---|')
    N = 22
    for i in range(N + 1):
        z = z1 - (z1 - z0) * i / N
        ев, ен = линия(ET, z), линия(EB, z)
        вс = [линия(МВ[k], z) for k in МВ if len(МВ[k]) > 1]
        нс = [линия(МН[k], z) for k in МН if len(МН[k]) > 1]
        вс = [x for x in вс if x is not None]
        нс = [x for x in нс if x is not None]
        if not вс or not нс or ев is None or ен is None:
            continue
        мв, мн = max(вс), min(нс)
        мв -= земля
        мн -= земля
        print('| %.2f W | %.3f / %.3f · %+.0f мм | %.3f / %.3f · %+.0f мм | %.3f / %.3f |'
              % ((z1 - z) / W, мв, ев, (мв - ев) * 1000, мн, ен, (мн - ен) * 1000,
                 мв - мн, ев - ен))
