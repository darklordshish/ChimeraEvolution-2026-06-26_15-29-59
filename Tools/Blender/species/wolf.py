# Шесть дуг, не три: гладкость бока — вопрос ПЛОТНОСТИ промежуточных объёмов, а не формы дуги.
# Каждая дуга из трёх звеньев: от позвонка вбок-вниз, широкая часть, схождение к грудине
#     ДУГА ЗАДАЁТСЯ ДВУМЯ КОНЦАМИ, А НЕ ТРЕМЯ СМЕЩЕНИЯМИ. Пока звенья набирались приращениями,
# нижний конец приходил куда придётся, и рёбра не смыкались на грудине — грудная клетка оставалась
# открытой снизу. Теперь у каждой дуги ЗАДАН нижний конец на грудине, а промежуточные точки из него
# выводятся: клетка замкнута по построению, а ширину я правлю, не разваливая схождение
# ОПОРНЫЕ ДУГИ, между ними рёбра ИНТЕРПОЛИРУЮТСЯ. Волк несёт тринадцать пар; семью бок читался
# лестницей, и это не вопрос вкуса — промежутки между дугами шире самой дуги видны как гофра.
# Опорных точек по-прежнему семь: править форму клетки надо в семи числах, а не в тринадцати
RIB_KEY = [   # (attach вдоль грудного, полуширина, конец на грудине (x, y, z))
    (0.98, .062, (.030, .742,  .150)),
    (0.86, .086, (.036, .706,  .078)),
    (0.72, .104, (.040, .684,  .000)),
    (0.56, .114, (.044, .668, -.082)),
    (0.40, .115, (.050, .666, -.160)),
    (0.24, .108, (.058, .684, -.238)),
    (0.08, .092, (.068, .730, -.310)),
]
RIB_N = 12


def _rib(t):
    """Дуга между опорными: t от 0 (краниальная) до 1 (каудальная)."""
    f = t * (len(RIB_KEY) - 1)
    i = min(int(f), len(RIB_KEY) - 2)
    k = f - i
    a, b = RIB_KEY[i], RIB_KEY[i + 1]
    return (a[0] + (b[0] - a[0]) * k, a[1] + (b[1] - a[1]) * k,
            tuple(a[2][j] + (b[2][j] - a[2][j]) * k for j in range(3)))


