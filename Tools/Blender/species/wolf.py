SK_O = (1.273, 0.470)                # затылочный мыщелок: (Y, Z)


def SK(px, py, x=0.0):
    """Пиксель профиля черепа → точка на живом волке. Один перевод на всю голову.

    Начало (52, 193) — сам мыщелок, а не «где-то там сзади». Первые прикидки (33, 187) и (28, 82)
    лежали ВНЕ кости, на фоне: наложение точек на пластину показало это за один взгляд, а по числам
    ошибка выглядела бы правдоподобно — просто череп на 5% длиннее."""
    u, v = (px - 52) * SK_S, (193 - py) * SK_S
    c, s = math.cos(SK_PITCH), math.sin(SK_PITCH)
    return (x, SK_O[0] + u * s + v * c, SK_O[1] + u * c - v * s)


