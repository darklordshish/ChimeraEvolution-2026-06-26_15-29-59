"""СИЛУЭТНЫЙ ГРАФ ЕЖА — поставка 6 модельной линии. Устройство — как у волка и лося (`../wolf/graph.py`).

СИЛУЭТ ЕЖА — КУПОЛ ИГЛ. Поле даёт купол-«яйцо» от земли до верха (юбка игл и мех брюха закрывают ноги целиком), рыльце
выходит из-под козырька игл спереди внизу. САМИ ИГЛЫ — НЕ ПОЛЕ: это части органа «Иглы» на месте `Шкура`
(`organs_layout.py`), поэтому `Шкура` не гасится. Сними орган — купол останется, иглы уйдут: так и должно быть.

ОТКУДА ЧИСЛА. `ref/photo/hedgehog_side_REFERENCE.jpg` (профиль, асфальт, открыт 17.09), сетка 10–50 px:
  земля      y = 1015 px  (среднее: передняя лапа 990, юбка сзади 1040 — кадр чуть сверху)
  верх игл   y =  322 px, x = 640 px
  масштаб    0.90 м / 693 px — калибр игровой: верх игл = высота капсулы ежа (0.9), верх туши мест был 0.81
Ширины — `hedgehog_front_REFERENCE.jpg` (анфас, отклонение ~12°, камера выше — высоту по нему не мерить): юбка игл
≈ 0.95 высоты, голова по щекам 0.42 ширины юбки, мочка 0.07.
Координаты: Y от земли, Z вперёд (на снимке ёж смотрит ВПРАВО: Z = (x − MID)·S), X вбок.

ЧЕГО В ГРАФЕ НЕТ: иглы, рыльце (клин Пасти), мочка, глаза, уши, задние стопы — детали.
ПЕРЕДНИЕ ЛАПКИ — ПОЛЕМ: органа на слоте `Руки` у ежа нет (хватки нет), куски органа вешать некуда.

Запуск:  python graph.py [--out путь]
"""
import argparse
import importlib.util
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def _wolf_graph():
    spec = importlib.util.spec_from_file_location('wolf_graph', os.path.join(HERE, '..', 'wolf', 'graph.py'))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


_W = _wolf_graph()
to_bones = _W.to_bones

# ── СНИМОК → МЕТРЫ ──────────────────────────────────────────────────────────────────────────────────
GROUND_PX, TOP_PX, MID_X_PX = 1015.0, 322.0, 835.0
TOP_Y = 0.90
S = TOP_Y / (GROUND_PX - TOP_PX)


def px(x, y):
    """Пиксель снимка → (Z, Y). Ёж смотрит вправо."""
    return ((x - MID_X_PX) * S, (GROUND_PX - y) * S)


PHOTO = {
    'иглы_верх':        (640, 322),
    'иглы_зад_верх':    (400, 395),
    'иглы_перед_1':     (880, 370),
    'иглы_перед_2':     (1000, 410),
    'иглы_перед_3':     (1100, 467),
    'козырёк':          (1390, 580),   # передний край игл над лбом
    'зад':              (275, 700),
    'юбка_зад':         (330, 1040),
    'кромка_игл_зад':   (330, 950),    # где кончаются иглы и начинается мех
    'кромка_игл_бок':   (700, 880),
    'кромка_игл_перед': (1100, 800),
    'основание_черепа': (1170, 720),
    'ухо':              (1235, 703),
    'глаз':             (1283, 740),
    'кончик_носа':      (1396, 857),
    'подбородок':       (1336, 879),
    'лапа_п':           (1165, 970),   # передняя лапа на земле, середина
}


def P(name):
    return px(*PHOTO[name])


X_FORE, X_HIND = 0.24, 0.24
z_skull, y_skull = P('основание_черепа')
z_nose, y_nose = P('кончик_носа')
z_pawf, _ = P('лапа_п')

# ПОЛЕ КУПОЛА — ВНУТРИ КОНТУРА ИГЛ на их вылет: верх поля 0.80 (+ полклетки роста), иглы дотягивают до 0.90
BODY_Y = 0.40


def node(name, socket, parent, a, b, r0, r1, section=1.0, depth=1.0, blend=0.0, mirror=False):
    return dict(name=name, socket=socket, parent=parent, a=a, b=b, r0=r0, r1=r1,
                section=section, depth=depth, blend=blend, mirror=mirror)


# КУПОЛ: узел `хребет` горизонтален (кадр места `Шкура` совпадает с мировым — иглы считать проще), яйцо даёт сужение
SPINE_A = (0.0, BODY_Y, -0.40)
SPINE_B = (0.0, BODY_Y, 0.20)
SPINE_R0, SPINE_R1, SPINE_SECTION = 0.40, 0.33, 0.90
VISOR_A, VISOR_B, VISOR_R0, VISOR_R1, VISOR_SECTION = (0.0, 0.44, 0.10), (0.0, 0.48, 0.50), 0.28, 0.14, 0.95


def build_nodes():
    head_len = 0.16
    t = math.atan2(y_nose - y_skull, z_nose - z_skull)
    head_a = (0.0, y_skull, z_skull)
    head_b = (0.0, y_skull + head_len * math.sin(t), z_skull + head_len * math.cos(t))
    return [
        node('хребет', 'хребет', '', SPINE_A, SPINE_B, SPINE_R0, SPINE_R1, section=SPINE_SECTION, blend=0.12),
        # КОЗЫРЁК: иглы над лбом выступают вперёд до Z 0.72 на высоте 0.57 (снимок) — голова уходит под него
        node('козырёк', 'хребет', 'хребет', VISOR_A, VISOR_B, VISOR_R0, VISOR_R1, section=VISOR_SECTION, blend=0.12),
        # ГРУДЬ — слот `Сердце`, целиком внутри купола: при конце на Z 0.25 оболочка груди выходила у лица сбоку от рыльца
        node('грудь', 'Сердце', 'хребет', (0.0, 0.34, -0.25), (0.0, 0.33, 0.08), 0.22, 0.22, blend=0.12),
        node('шея', 'шея', 'хребет', (0.0, y_skull - 0.01, 0.30), (0.0, y_skull, z_skull), 0.15, 0.14, blend=0.10),
        # ГОЛОВА — череп до глаз; рыльце — клин Пасти. Ось как на снимке: основание черепа → кончик носа
        node('голова', 'голова', 'шея', head_a, head_b, 0.14, 0.12, section=1.0, depth=1.05, blend=0.08),
        # ПЕРЕДНИЕ ЛАПКИ — полем: плечо в туше, кисть плоско на земле (органа «Руки» у ежа нет)
        # плечо отведено назад от головы: у лица сходились оболочки `голова` и `Руки`, и шов делил клетки несимметрично
        # (замер вершин: слева `Руки` брали клетки рядом с рыльцем, справа — `голова`) — на анфасе выходил бугор с одной стороны
        node('плечо', 'Руки', 'хребет', (X_FORE, 0.30, 0.16), (X_FORE, 0.12, 0.24), 0.10, 0.07, blend=0.10, mirror=True),
        node('кисть', 'Руки', 'плечо', (X_FORE, 0.06, 0.22), (X_FORE, 0.055, z_pawf + 0.04), 0.06, 0.055,
             section=1.25, depth=0.95, blend=0.06, mirror=True),
        # ЗАДНИЕ — бедро и голень полем, стопа — блок `лапа` органа «Ежиные ноги»
        node('бедро', 'Ноги', 'хребет', (X_HIND, 0.32, -0.40), (X_HIND, 0.16, -0.36), 0.12, 0.085, blend=0.10, mirror=True),
        node('голень', 'Ноги', 'бедро', (X_HIND, 0.16, -0.36), (X_HIND, 0.10, -0.33), 0.085, 0.07, blend=0.06, mirror=True),
        # ХВОСТ — обрубок под юбкой сзади
        node('хвост', 'Хвост', 'хребет', (0.0, 0.16, -0.66), (0.0, 0.12, -0.76), 0.06, 0.05, blend=0.05),
    ]


HIDES = ['хребет', 'шея', 'голова', 'Сердце', 'Руки', 'Ноги', 'Хвост']


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=os.path.join(HERE, 'out', 'ezh-graph-draft.json'))
    args = ap.parse_args()
    nodes = build_nodes()
    bones = to_bones(nodes)
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, 'w', encoding='utf-8') as f:
        json.dump(dict(species='Ёж', hides=HIDES, nodes=bones), f, ensure_ascii=False, indent=2)
    print('узлов', len(bones), '→', args.out)
    for n in nodes:
        print('  %-8s %-7s (%.2f %.2f %.2f) → (%.2f %.2f %.2f)  r %.3f→%.3f' %
              ((n['name'], n['socket']) + tuple(n['a']) + tuple(n['b']) + (n['r0'], n['r1'])))


if __name__ == '__main__':
    main()
