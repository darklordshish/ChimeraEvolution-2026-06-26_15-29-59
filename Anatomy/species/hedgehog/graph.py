"""СИЛУЭТНЫЙ ГРАФ ЕЖА — ХЕДЖХАЛК, поставка 22 модельной линии. Устройство — как у волка и лося (`../wolf/graph.py`).

ЧТО ЭТО. Решение геймдизайнера 25.09: база ежа — лист Хеджхалка `ref/sheet/yozh-hedzhhalk-baza_chatgpt_2026-09-24.png`
(лабораторный мутант по спеке `2026-07-22-yozh-hedgehalk-design.md`), 3D-образец по нему — `ref/mv/yozh_mv_A.glb`.
Прежний граф (поставки 6–21) был природным ежом с фото: купол до земли, лапы под юбкой игл, рыльце под козырьком.
Подкрутка его чисел по одному не сходилась — суставы сидели в точках другого зверя, — поэтому граф снят заново.

ОТКУДА ЧИСЛА. Профиль листа (SIDE LEFT, ёж смотрит ВЛЕВО), сетка 10 px на увеличении ×5 (`out/setka-profil.png`):
  земля        y = 370 px
  верх игл     y = 235 px (без гребня трубок) — 0.90 м, калибр игровой: прежняя высота ежа, капсула 0.9
  масштаб      0.90 м / 135 px;  Z = (540 − x)·S — вперёд к носу, Y = (370 − y)·S — от земли, X вбок
В профиль Хеджхалк ДЛИННЫЙ (нос — хвост 1.6 м): «компактным» его делает ракурс 3/4. Отличия от природного ежа —
огромная голова (0.43 × 0.40 м, нос на 0.47 м), глубокая туша (0.25…0.67 м), лапы согнуты, пальцы вынесены вперёд.

ЧЕГО В ГРАФЕ НЕТ: иглы и гребень трубок (органы «Иглы» и «Игломёт», `organs_layout.py`), рыло с клыками (блок Пасти),
мочка, глаза, уши, задние стопы — детали. Передние лапы — полем: органа на слоте `Руки` у ежа нет, когтям пока негде
висеть (вопрос механикам).

Запуск:  python graph.py [--out путь]
"""
import argparse
import importlib.util
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def _wolf_graph():
    spec = importlib.util.spec_from_file_location('wolf_graph', os.path.join(HERE, '..', 'wolf', 'graph.py'))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


_W = _wolf_graph()
to_bones = _W.to_bones

# ── ЛИСТ → МЕТРЫ ────────────────────────────────────────────────────────────────────────────────────
GROUND_PX, TOP_PX, MID_X_PX = 370.0, 235.0, 540.0
TOP_Y = 0.90
S = TOP_Y / (GROUND_PX - TOP_PX)


def px(x, y):
    """Пиксель листа → (Z, Y). Ёж смотрит влево."""
    return ((MID_X_PX - x) * S, (GROUND_PX - y) * S)


# Замеры с профиля листа, пиксели. Узлы берутся ИЗ НИХ, суставы под иглами — с явной поправкой
PHOTO = {
    'кончик_носа':      (385, 300),
    'низ_челюсти':      (405, 322),
    'глаз':             (416, 287),
    'ухо':              (426, 262),
    'темя':             (432, 262),
    'основание_черепа': (450, 280),
    'горло':            (440, 325),
    'холка':            (480, 268),
    'спина':            (540, 272),
    'круп':             (610, 285),
    'зад':              (632, 320),
    'низ_груди':        (470, 335),
    'брюхо':            (540, 332),
    'плечевой':         (480, 300),
    'локоть':           (488, 340),
    'запястье':         (462, 358),
    'пальцы_п':         (440, 368),
    'тазобедренный':    (590, 295),
    'колено':           (592, 335),
    'пятка':            (618, 352),
    'пальцы_з':         (590, 368),
}


def P(name, dy=0.0):
    z, y = px(*PHOTO[name])
    return z, y + dy


X_FORE, X_HIND = 0.25, 0.24             # лапы вынесены из-под туши (анфас листа: широкая припавшая стойка)
X_IN = 0.12                             # плечевой и тазобедренный — внутри туши
# ПРИПАВШАЯ СТОЙКА (25.09): на листе локти и колени развёрнуты НАРУЖУ, лапы расставлены, кисти вынесены вперёд-наружу.
# Столбики под телом читались собакой на выставке. Граф — поза покоя: пока нет анимации, в игре видна она
# ...ОДНОЙ ЛИНИЕЙ, без зигзага (плечо наружу → предплечье внутрь → кисть наружу читалось переломом), и из-под туши:
# туша шире (SPINE_SECTION 1.20), лапы не выходят за её бок
X_ELBOW, X_WRIST, X_TOES_F = 0.29, 0.25, 0.26   # локоть наружу (критик r2)
X_KNEE, X_HOCK, X_TOES_H = 0.24, 0.24, 0.26
z_skull, y_skull = P('основание_черепа')
z_nose, y_nose = P('кончик_носа')


def node(name, socket, parent, a, b, r0, r1, section=1.0, depth=1.0, blend=0.0, mirror=False):
    return dict(name=name, socket=socket, parent=parent, a=a, b=b, r0=r0, r1=r1,
                section=section, depth=depth, blend=blend, mirror=mirror)


def w(name, x=0.0, dy=0.0, dz=0.0):
    z, y = P(name)
    return (x, y + dy, z + dz)


# ТУША: ось посередине между верхом тела под иглами и брюхом; от крупа к холке, плечи выше крупа (горб к плечам)
# ТУША ТЯЖЕЛЕЕ СПЕРЕДИ (25.09, геймдизайнер: «жопа с ручками»; профиль листа): у плеч тело 0.23…0.68 м (глубина 0.45),
# у таза 0.23 м в глубину, брюхо подтянуто к задним лапам, холка — самая высокая точка. Прежняя туша была ровной
# колбасой с большим круглым задом. Ось идёт от таза (выше и тоньше) к плечам (ниже центра, толще)
# ...и КЛИНОМ: без игл туша была ровной трубой — круп на 0.66 почти вровень с холкой. По листу верх крупа 0.57, глубина
# у таза 0.24: спина заметно опускается от плеч к крупу
SPINE_A = (0.0, 0.45, -0.38)
SPINE_B = (0.0, 0.47, 0.30)
SPINE_R0, SPINE_R1, SPINE_SECTION = 0.12, 0.22, 1.20   # круп уже (критик r1: −15 %)
# ЗАГРИВОК — горб плеч под гребнем (имя узла прежнее: на нём считаются иглы в `organs_layout.py`)
VISOR_A, VISOR_B, VISOR_R0, VISOR_R1, VISOR_SECTION = (0.0, 0.55, 0.10), (0.0, 0.58, 0.42), 0.18, 0.16, 1.10


def build_nodes():
    return [
        node('хребет', 'хребет', '', SPINE_A, SPINE_B, SPINE_R0, SPINE_R1, section=SPINE_SECTION, blend=0.12),
        node('козырёк', 'хребет', 'хребет', VISOR_A, VISOR_B, VISOR_R0, VISOR_R1, section=VISOR_SECTION, blend=0.12),
        # ГРУДЬ — слот `Сердце`, внутри туши, опускается к низу груди
        node('грудь', 'Сердце', 'хребет', (0.0, 0.40, 0.00), (0.0, 0.41, 0.40), 0.13, 0.16, section=1.05, blend=0.12),   # глубокая, но меньше (геймдизайнер 25.09: «грудь чуть меньше»)
        # ШЕЯ — короткая и толстая: голова сидит почти на плечах
        # ...и ВЫСОКАЯ: начало на уровне загривка, иначе между холкой и черепом провал («надлом в холке», геймдизайнер 25.09)
        node('шея', 'шея', 'хребет', (0.0, 0.57, 0.36), (0.0, y_skull, z_skull), 0.20, 0.18, blend=0.12),
        # ГОЛОВА — череп от затылка до глаз, крупный (высота головы на листе 0.40 м); рыло — клин Пасти
        node('голова', 'голова', 'шея', (0.0, y_skull - 0.02, z_skull), w('глаз', dy=0.01, dz=-0.07),   # череп — лоб и затылок, к глазам не доходит: морда — блок
             0.19, 0.14, section=0.95, depth=0.85, blend=0.08),   # сплющен по высоте (критик r2: «мяч с коробкой»)
        # ПЕРЕДНИЕ ЛАПЫ — полем: плечо в туше → локоть → запястье, кисть плоско на земле, пальцы вперёд
        # ПЛЕЧО И БЕДРО НАЧИНАЮТСЯ ВНУТРИ ТУШИ (X_IN) и выходят к локтю/колену: с началом на поверхности (X_FORE) плечо
        # торчало трубкой-«ручкой», приставленной к боку
        # ЛАПЫ (критик r1, 25.09): перёд тяжелее зада — плечо и предплечье мощные, с ПЕРЕХВАТОМ к запястью, кисть широкая
        # и короткая (веер); передние стоят под лопаткой почти отвесно, задние под тазом. Прежние ровные трубки одной
        # толщины читались «сосисками» (толстые — валенками, тонкие — палками): держит лапу ритм, а не толщина
        node('плечо', 'Руки', 'хребет', w('плечевой', X_IN, dy=0.06), w('локоть', X_ELBOW, dy=0.03, dz=-0.03),
             0.15, 0.11, blend=0.10, mirror=True),
        node('предплечье', 'Руки', 'плечо', w('локоть', X_ELBOW, dy=0.03, dz=-0.03), w('запястье', X_WRIST, dy=0.05, dz=-0.08),
             0.105, 0.062, blend=0.05, mirror=True),
        node('кисть', 'Руки', 'предплечье', w('запястье', X_WRIST, dy=0.03, dz=-0.08), w('пальцы_п', X_TOES_F, dy=0.03, dz=-0.10),
             0.062, 0.050, section=2.00, depth=0.50, blend=0.03, mirror=True),
        node('бедро', 'Ноги', 'хребет', w('тазобедренный', X_IN, dy=-0.02), w('колено', X_KNEE, dz=0.04),
             0.12, 0.085, blend=0.10, mirror=True),
        node('голень', 'Ноги', 'бедро', w('колено', X_KNEE, dz=0.04), w('пятка', X_HOCK, dy=0.02, dz=0.10),
             0.080, 0.050, blend=0.05, mirror=True),
        # СТОПА — ПОЛЕМ, как кисть (обе пары одинаково): орган ног ворует химера, повесить на него передние лапы нельзя
        node('стопа', 'Ноги', 'голень', w('пятка', X_HOCK, dy=-0.02, dz=0.10), w('пальцы_з', X_TOES_H, dy=0.04, dz=0.05),
             0.055, 0.060, section=1.60, depth=0.58, blend=0.03, mirror=True),
        # ХВОСТ — КОРОТКИЙ ОБРУБОК, СВИСАЕТ ВНИЗ под иглами у крупа (лист), а не продолжает тушу назад
        node('хвост', 'Хвост', 'хребет', (0.0, 0.40, -0.50), (0.0, 0.29, -0.57), 0.055, 0.042, blend=0.05),
    ]


HIDES = ['хребет', 'шея', 'голова', 'Сердце', 'Руки', 'Ноги', 'Хвост']


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=os.path.join(HERE, 'out', 'ezh-graph-draft.json'))
    args = ap.parse_args()
    nodes = build_nodes()
    bones = to_bones(nodes)
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, 'w', encoding='utf-8') as f:
        json.dump(dict(species='Ёж', hides=HIDES, nodes=bones), f, ensure_ascii=False, indent=2)
    print('узлов', len(bones), '→', args.out)
    for n in nodes:
        print('  %-10s %-7s (%.2f %.2f %.2f) → (%.2f %.2f %.2f)  r %.3f→%.3f' %
              ((n['name'], n['socket']) + tuple(n['a']) + tuple(n['b']) + (n['r0'], n['r1'])))


if __name__ == '__main__':
    main()
