def arm_level(t, upper):
    a, b = (SHOULDER, ELBOW) if upper else (ELBOW, WRIST)
    ra, rb = (REF_SHOULDER, REF_ELBOW) if upper else (REF_ELBOW, REF_WRIST)
    yr = ra[1] + (rb[1] - ra[1]) * t
    ax_ref = ra[0] + (rb[0] - ra[0]) * t
    cos = abs(ra[1] - rb[1]) / math.hypot(rb[0] - ra[0], rb[1] - ra[1])
    x0, x1 = front(yr, 0.15, 0.40)
    hw = (x1 - x0) / 2 * cos
    shift = ((x0 + x1) / 2 - ax_ref) * cos
    c = lerp(a, b, t)
    zb, zf = (ARM_PROFILE_UPPER if upper else ARM_PROFILE_FORE)[t]
    za, zbx = (REF_ARM_Z[0], REF_ARM_Z[1]) if upper else (REF_ARM_Z[1], REF_ARM_Z[2])
    c = (c[0] + shift, c[1], round(c[2] + (zb + zf) / 2 - (za + (zbx - za) * t), 4))   # сдвиг от оси руки листа — на нашу ось
    return c, hw + ARM_GROW + arm_fit(t, upper), (zf - zb) / 2 + ARM_GROW


