def torso_surface(x, y, back=False):
    """Z поверхности торса-лофта в точке (x, y): эллипс уровня, спереди или сзади."""
    c, hw, hd = torso_level(y)
    k = math.sqrt(max(0.0, 1.0 - (x / hw) ** 2))
    return c[2] - hd * k if back else c[2] + hd * k


def groove(name, socket, parent, pts, width, deep, back=False, mirror=False, blend=0.010):
    """БОРОЗДА ПО ПОВЕРХНОСТИ торса: ломаная (x, y) → узлы вычитания шириной `width` и глубиной `deep`, м. Лоу-поли
    рисует мышцу сменой плоскости, а не щелью: борозда широкая и пологая — ось капсулы СНАРУЖИ поверхности на r − deep,
    r = (w²/4 + d²) / 2d. Узкая глубокая (ось на поверхности) на клетке 0.021 читалась прорезью (кадр 23.09)."""
    out = []
    r = round((width * width / 4 + deep * deep) / (2 * deep), 4)
    lift = r - deep
    P = [(x, y, torso_surface(x, y, back) + (-lift if back else lift)) for x, y in pts]
    for i in range(len(P) - 1):
        out.append(node('%s%d' % (name, i + 1) if len(P) > 2 else name, socket, parent, _round3(P[i]), _round3(P[i + 1]),
                        r, r, blend=blend, mirror=mirror, layer=CUT))
    return out


