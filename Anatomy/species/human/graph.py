def torso_level(y):
    x0, x1 = front(y, -0.06, 0.06)
    hw = (x1 - x0) / 2
    zb, zf = side(y)
    if y < 1.08:
        hw -= 0.006; zf -= 0.015; zb += 0.006
    if 1.14 < y < 1.42:
        zb += 0.005
    return (0.0, y, (zb + zf) / 2), hw, (zf - zb) / 2


