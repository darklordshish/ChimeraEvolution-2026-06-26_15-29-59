def _near(view, y, spread=1):
    rows = views()[view]['rows']
    i = min(range(len(rows)), key=lambda k: abs(rows[k]['y'] - y))
    return rows[max(0, i - spread): i + spread + 1]


def _median(v):
    v = sorted(v)
    return v[len(v) // 2] if len(v) % 2 else (v[len(v) // 2 - 1] + v[len(v) // 2]) / 2


def front(y, lo, hi):
    """Анфас на высоте y: объединение отрезков, чья середина в [lo, hi] (правая сторона; левая зеркалится, края
    усредняются по обеим сторонам и трём строкам). → (x0, x1) или None."""
    x0s, x1s = [], []
    for r in _near('front', y):
        for sgn in (1.0, -1.0):
            segs = [(a, b) if sgn > 0 else (-b, -a) for a, b in r['x']]
            segs = [s for s in segs if lo <= (s[0] + s[1]) / 2 <= hi]
            if segs:
                x0s.append(min(s[0] for s in segs)); x1s.append(max(s[1] for s in segs))
    return (_median(x0s), _median(x1s)) if x0s else None


def side(y):
    """Профиль на высоте y: крайние Z силуэта (сзади, спереди), уже со сдвигом `DZ`."""
    rows = _near('side', y)
    zb = _median([min(s[0] for s in r['z']) for r in rows if r['z']])
    zf = _median([max(s[1] for s in r['z']) for r in rows if r['z']])
    return zb + DZ, zf + DZ


