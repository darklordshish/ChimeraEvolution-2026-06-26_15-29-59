# ── ЛОФТ ─────────────────────────────────────────────────────────────────────────────────────────────
def loft(prefix, socket, parent, levels, blend=0.008, mirror=False, k_first=1.0, k_last=1.0, uniform=False, overlap=0.0):
    """Узлы между соседними уровнями `levels` = [(центр, полуширина, полуглубина)]. Радиус узла — меньшая из полуосей,
    `section`/`depth` — отношения полуосей к радиусу (среднее по концам). Торец капсулы уходит за уровень на радиус и
    вдоль узла НЕ сплющивается, поэтому у крайних узлов радиус уменьшен (`k_first`, `k_last`), а сечение растянуто — так
    торец цепочки не торчит за контур листа.
    `uniform` — ОДНО отношение полуосей на всю цепочку (конечности): при своём у каждого узла сечения соседей на стыке
    не совпадали, и на клетке 0.021 бедро и голень шли кольцами, как гусеница (кадр 23.09). Радиус уровня тогда —
    наименьшие квадраты по обеим полуосям.
    СМЕШЕНИЕ МАЛОЕ (0.008): лофт непрерывен и без него, а мягкий минимум там, где два соседних узла одинаково близки,
    добавляет валик ~blend/4 — при 0.02 это кольцо 5 мм на каждом стыке, на клетке 0.021 видимое.
    `overlap` — СТЫКИ ВНАХЛЁСТ: узел заходит в соседний на эту долю его длины. Встык при разном отношении полуосей у соседей
    оба торца на стыке сходятся, и между ними остаётся надрез поперёк конечности — рука читалась «гусеницей» с бороздками
    через 8–10 см (рецензия 23.09). Внахлёст на стыке оба сечения полные, надреза нет"""
    out = []
    n = len(levels) - 1
    rad = [min(w, d) for _, w, d in levels]
    if uniform:
        sec = sum(w / min(w, d) for _, w, d in levels) / len(levels)
        dep = sum(d / min(w, d) for _, w, d in levels) / len(levels)
        rs = [(w * sec + d * dep) / (sec * sec + dep * dep) for _, w, d in levels]
    for i in range(n):
        (c0, w0, d0), (c1, w1, d1) = levels[i], levels[i + 1]
        k = k_first if i == 0 else (k_last if i == n - 1 else 1.0)
        # ...продлённый конец идёт СОБСТВЕННЫМ СУЖЕНИЕМ узла (линейно за уровень), с ограничением: не толще соседей и не тоньше
        # 0.8 от них. Так на обоих уровнях ширина точная, а заход в соседа не раздувает. Прежде конец нёс полное сечение
        # уровня дальше (рука толще на 1–1.5 см), потом — ширину соседа (сечение на уровне проседало, икра −1 см)
        if overlap > 0:
            L = lambda p, q: v_len(v_sub(p, q))
            Li = max(1e-6, L(c1, c0))
            def extend(w_a, w_b, w_n, t):
                w = w_a + (w_b - w_a) * t
                return min(max(w, 0.8 * min(w_a, w_b, w_n)), max(w_a, w_b, w_n))
            if i > 0:
                t = -overlap * L(levels[i - 1][0], c0) / Li
                c0n = _round3(lerp(c0, levels[i - 1][0], overlap))
                w0, d0 = extend(w0, w1, levels[i - 1][1], t), extend(d0, d1, levels[i - 1][2], t)
            else:
                c0n = c0
            if i < n - 1:
                t = 1 + overlap * L(levels[i + 2][0], c1) / Li
                c1n = _round3(lerp(c1, levels[i + 2][0], overlap))
                w1, d1 = extend(levels[i][1], w1, levels[i + 2][1], t), extend(levels[i][2], d1, levels[i + 2][2], t)
            else:
                c1n = c1
            c0, c1 = c0n, c1n
        if uniform:
            r0, r1 = k * rs[i], k * rs[i + 1]
            sc, dp = sec / k, dep / k
            out.append(node('%s%d' % (prefix, i + 1), socket, parent, c0, c1, round(r0, 4), round(r1, 4),
                            round(sc, 3), round(dp, 3), blend, mirror))
            continue
        r0, r1 = k * min(w0, d0), k * min(w1, d1)
        sec = (w0 / r0 + w1 / r1) / 2
        dep = (d0 / r0 + d1 / r1) / 2
        out.append(node('%s%d' % (prefix, i + 1), socket, parent, c0, c1, round(r0, 4), round(r1, 4),
                        round(sec, 3), round(dep, 3), blend, mirror))
    return out


def _round3(p):
    return tuple(round(c, 4) for c in p)


