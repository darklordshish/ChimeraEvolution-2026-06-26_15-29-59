"""ВОЛК НА ДВУНОГОМ — тело волка на плане человека (спека `2026-10-08-vid-na-chuzhom-plane.md`, срез 1): числа 17 групп
шаблона двуногого и блок `head`, снятые с последней колонки листа ступеней оборотня 08.10 (`25089f8`; с 08.10 —
`Референсы/архив/2026-10-08-оборотень-stupeni-25089f8/`, действующий лист — `Референсы/витрина/оборотень/ступени.png`).

Запуск (заготовка — вне handoff/, иначе импорт примет её как тело волка):
  unity command run_script --file Tools/Agent/PlanBodies.cs --entry PlanBodies.Export --args '["Человек","Волк","<заготовка>"]'
  python Anatomy/species/wolf/na_dvunogom.py <заготовка> Docs/models/handoff/volk-na-dvunogom.json
Сверка — Stand.Stages с g2 = 1 рядом с маской `volk-*.png`; IoU анфаса 08.10 (итерация 1): шасси 0.440, ступень 2 — 0.459.

Числа человека × множители по группам.
Нормировка — по РОСТУ фигуры (скелет химеры человеческий, торс не удлиняется): у листа плечевой пояс ×1.36, плечо ×1.54,
предплечье ×1.75, бедро ×1.19, голень ×0.66, грудь анфас ×1.18, в профиль до ×1.65 (с гривой).
Веретена (r = полудлина) толщают через section/depth; капсулы торса, дельты, трапеция, грудная, ягодица — через r."""
import json, sys
src, dst = sys.argv[1], sys.argv[2]
d = json.load(open(src, encoding='utf-8'))
# ИТЕРАЦИЯ 2 (08.10, новая редакция листа Codex): плечи/грудь анфас к цели ×1.2 (было ×1.36 со старых масок) —
# дельты и трапеция мягче; глубина груди в профиль 0.22 → 0.52 роста (с гривой) — грудная клетка глубже; голова шире ×1.45
# (геймдизайнер: «голова волка маловата»); живот — верх в груди, низ подобран: ступенька на стыке груди и живота (кадр 08.10)
# ИТЕРАЦИЯ 3 (09.10, волк по ортопаре; вердикт геймдизайнера по итерации 2: «голова крошечная, горб в районе живота»).
# ГОРБ ДАВАЛ НИЗ ГРУДИ: грудная клетка толстела с самого низа (r0 ×1.15 при глубине ×1.7) и живот кверху (×1.15) — масса
# стояла на уровне пупка. У цели листа грудь — бочка ПОД ПЛЕЧАМИ, живот подобран: низ груди как у человека, верх ×1.3,
# живот кверху тоньше человеческого
# ...и ШИРЕ: по поясам анфаса (ст.2 против цели, в долях роста) тело было уже на 22–28 % на всей высоте от таза до плеч —
# дельты, руки выше локтя, таз и бёдра прибавлены; предплечья — нет (при ×1.6 они торчали вбок «ушами», итерация 1)
R = {'таз': 1.25, 'грудная': 0.80, 'ягодица': 1.30, 'трапеция': 1.30,
     'дельта.перед': 1.35, 'дельта': 1.40, 'дельта.зад': 1.35}
R01 = {'живот': (0.95, 0.90), 'грудная клетка': (0.95, 1.22)}
T = {'широчайшая': 2.3, 'бицепс': 2.6, 'трицепс': 2.8, 'разгибатели': 1.4, 'сгибатели': 1.4,
     'квадрицепс': 2.2, 'задняя бедра': 2.0, 'икра': 0.8}
DEPTH = {'грудная клетка': 1.15, 'живот': 1.00}
# ГЛУБИНА РАСТЁТ ОТ ОСИ В ОБЕ СТОРОНЫ: у итерации 2 грудь ×1.7 вдувалась и назад — в профиль шар на спине от лопаток до
# поясницы, он и читался «горбом». Спина у верха груди держится на месте (`z` вперёд на прирост полуглубины), вся прибавка
# уходит в грудь; центр массы груди выше — к плечам
FORWARD = {'грудная клетка'}
SHIFT_U = {'грудная клетка': (0.05, 0.92)}       # начало выше на 0.05 торса, длина ×0.92
# ОТРЕЗКИ (доли торса, дополнение 3 письма механик): у оборотня на листе таз 0.42 роста, колено 0.25, скакательный 0.10 против
# 0.52 / 0.28 / 0.05 у человека — бедро ×0.7, голень ×0.6 (ниже скакательного — пясть стопы, её даёт аугмент ног). Суставы по
# силуэту читаются грубо, и длины ног садят всё тело — берётся осторожнее; плечо чуть короче, предплечье то же
SEG = {'локоть': 0.90, 'колено': 0.75, 'скакательный': 0.70}
import os
B = float(os.environ.get('BOOST', '1.0'))          # общая сила масс; 1.6 давала IoU 0.476, но предплечья торчали вбок «ушами»
LONG = {'бицепс': 1.8, 'трицепс': 1.7, 'разгибатели': 1.6, 'сгибатели': 1.6, 'квадрицепс': 1.3, 'задняя бедра': 2.5}
for g in d['groups']:
    n = g['name']
    if n in R:
        k = 1 + (R[n] - 1) * B
        g['r0'] *= k; g['r1'] *= k
    if n in T:
        k = 1 + (T[n] - 1) * B
        L = LONG.get(n, 1.0)            # веретено длиннее: r — полудлина; толщина = r·section, поэтому делим на L
        g['r0'] *= L; g['r1'] *= L
        g['section'] *= k / L; g['depth'] *= k / L
    if n in R01:
        g['r0'] *= R01[n][0]; g['r1'] *= R01[n][1]
    if n in DEPTH:
        back0 = g['r1'] / R01.get(n, (1, 1))[1] * g['depth']   # полуглубина верха у человека
        g['depth'] *= DEPTH[n]
        if n in FORWARD:
            g['z'] += g['r1'] * g['depth'] - back0
    if n in SHIFT_U:
        g['u'] += SHIFT_U[n][0]; g['len'] *= SHIFT_U[n][1]
    for f in ('u', 'len', 'r0', 'r1', 'x', 'z', 'section', 'depth'):
        g[f] = round(g[f], 4)
# ГОЛОВА — КАЛИБРОМ ГОЛОВЫ ВОЛКА (09.10). Узел головы человека идёт от шеи к темени (ось вверх, лицо — вбок от оси);
# волчий — от затылка к стопу. Повернуть человеческий узел носом вперёд нельзя: лицо и гнездо Пасти легли бы вниз. Поэтому
# голова остаётся «человеческой» по оси, а меры — волчьи: ширина головы волка 0.28 м против 0.15 у человека (×1.9),
# высота 0.30 против ~0.20 (длина узла ×1.4). Гнёзда едут за костью (`FollowNests`) — Пасть волка садится в калибр его
# головы. Шея — под гривой листа: ×2.2 / ×2.0 (в анфас шея с гривой у цели 0.26–0.32 роста против 0.09–0.12 у человека).
# Итерация 2 (×1.45 / ×1.5) с `KHead` 0.5 давала голову ×1.2 — «крошечная»
HEAD_R, HEAD_LEN, NECK_R = 1.90, 1.40, (2.2, 2.0)
h = d['head']
h.update(neckLen=round(h['neckLen'], 4), neckR0=round(h['neckR0'] * NECK_R[0], 4), neckR1=round(h['neckR1'] * NECK_R[1], 4),
         neckPitch=float(sys.argv[3]) if len(sys.argv) > 3 else 45.0,
         headLen=round(h['headLen'] * HEAD_LEN, 4), headR0=round(h['headR0'] * HEAD_R, 4), headR1=round(h['headR1'] * HEAD_R, 4),
         headPitch=float(sys.argv[4]) if len(sys.argv) > 4 else -45.0)
for sgm in d.get('segments', []):
    sgm['len'] = round(sgm['len'] * SEG.get(sgm['end'], 1.0), 4)
json.dump(d, open(dst, 'w', encoding='utf-8'), ensure_ascii=False, indent=2)
print('ok')
