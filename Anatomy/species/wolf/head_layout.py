# -*- coding: utf-8 -*-
"""РАСКЛАДКА ГОЛОВЫ ВОЛКА — калибр места `голова` и доли деталей на ней (поставка 3, письмо механик 17.09c §3).

КАК ЭТО СВЯЗАНО С ИГРОЙ. Место `голова` погашено графом и берёт у одноимённого узла ПОЗУ: начало места — в
начале узла, длинная ось (Z) — вдоль узла, +Y — к темени. Калибр (W × H × L) место держит СВОЙ, и от него
считаются доли всех деталей головы (`MorphBuilder.Place`):
    вдоль оси от начала узла  = (attach + attachOffset.z) · L
    к темени                  = attachOffset.y · H
    вбок                      = attachOffset.x · W

ОТКУДА ЧИСЛА. Точки сняты с `ref/photo/wolf_standing_1.jpg` (та же сетка и опоры, что у `graph.py`) и
переведены в кадр ГОЛОВЫ СНИМКА: начало — основание черепа под ушами, ось — к кончику носа. В этом кадре
голова одна и та же при любой посадке, поэтому точки переносятся на нейтральную голову графа как есть.
Ширины, которых профиль не даёт, — отдельной строкой с источником.

Калибр L — от основания черепа до кончика носа: лишняя против узла длина места и есть зона морды (клин).

Запуск:  python head_layout.py [--out путь]
"""
import argparse
import json
import math
import os

import graph as G

HERE = os.path.dirname(os.path.abspath(__file__))

# КЛЕТКА ПРОЕКТА — 0.042 (решение геймдизайнера 22.09: «как у человека, у всех»). Замеры поверхности — на обе клетки
GRAIN = 0.042

# ── ТОЧКИ ГОЛОВЫ НА СНИМКЕ, px исходника ─────────────────────────────────────────────────────────────
HEAD_PX = {
    'основание_черепа': (1610, 280),   # сустав головы: под основанием ушей, на 8 см ниже линии загривка
    'кончик_носа':      (1935, 400),
    'мочка':            (1915, 405),   # центр мочки
    'глаз':             (1765, 268),
    'ухо_середина':     (1650, 110),
    'темя':             (1630, 175),   # верх черепа у основания ушей
    'стоп':             (1800, 260),   # перелом лба в спинку носа
    'угол_рта':         (1760, 420),
    'подбородок':       (1880, 460),
    'челюсть_низ':      (1700, 470),   # низ челюсти под глазом
}


def world(name):
    z, y = G.px(*HEAD_PX[name])
    return (y, z)


def photo_frame():
    oy, oz = world('основание_черепа')
    ny, nz = world('кончик_носа')
    dy, dz = ny - oy, nz - oz
    L = math.hypot(dy, dz)
    u = (dy / L, dz / L)                 # вдоль головы
    v = (u[1], -u[0])                    # к темени: перпендикуляр, повёрнутый вверх
    if v[0] < 0:
        v = (-v[0], -v[1])
    return (oy, oz), u, v, L


def local(name):
    (oy, oz), u, v, _ = photo_frame()
    y, z = world(name)
    d = (y - oy, z - oz)
    return (d[0] * u[0] + d[1] * u[1], d[0] * v[0] + d[1] * v[1])   # (вдоль, к темени)


# ── КАЛИБР МЕСТА «голова» ────────────────────────────────────────────────────────────────────────────
_, _, _, L_PHOTO = photo_frame()
L = round(L_PHOTO + 0.005, 3)            # до переднего края мочки
# Высота: от низа челюсти до темени у основания ушей, по снимку
H = round(local('темя')[1] - local('челюсть_низ')[1], 3)
# Ширина: профиль её не даёт. Скуловая ширина псовых ≈ 0.55 длины черепа (пластина `skeleton/wolf_skull_plate.jpg`,
# дорсальный аспект) плюс мех на скулах по 3 см (`photo/wolf_head_front.jpg`)
W = round(0.55 * L + 0.06, 3)

NECK_CALIBRE = (0.220, 0.300, 0.380)
MUZZLE_TILT = 8.0                        # наклон клина носом вниз, градусы (+X — нос вниз)     # калибр места `шея` у волка — от него считается sizeRel головы


def rel(abs_size, cal):
    return tuple(round(a / c, 3) for a, c in zip(abs_size, cal))


def place(name, attach, along, up, lateral, size, euler=(0.0, 0.0, 0.0), note=''):
    """Деталь головы: положение в метрах кадра головы → доли калибра."""
    return dict(name=name, attach=attach,
                attachOffset=[round(lateral / W, 3), round(up / H, 3), round(along / L - attach, 3)],
                sizeRel=list(rel(size, (W, H, L))), baseEuler=list(euler), note=note,
                metres=dict(along=round(along, 3), up=round(up, 3), lateral=round(lateral, 3), size=list(size)))


def layout():
    eye_a, eye_b = local('глаз')
    ear_a, ear_b = local('ухо_середина')
    nose_a, nose_b = local('мочка')
    # мочка на самом конце клина, наполовину наружу: по снимку её центр на 2 см позади кончика носа, и в клине она
    # тонула целиком — у блока нет мягкой мочки поверх кости, как у зверя
    nose_a = L - 0.003
    stop_a, stop_b = local('стоп')
    jaw_a, jaw_b = local('челюсть_низ')

    # ПАСТЬ = МОРДА. Коробка места от 0.095 (заход клина в череп на свою толщину) до кончика носа, по высоте от
    # низа челюсти до стопа. Центр коробки и есть точка места
    # МОРДА НИЖЕ И НАКЛОНЕНА НОСОМ ВНИЗ (письмо механик 17.09e §5 п. 2, перемерено на 0.042 — 22.09): коробка от низа челюсти
    # до стопа (0.25) стояла ровно, и низ клина у основания (−0.155 в кадре головы) уходил на 5 см ниже низа поля головы
    # (−0.10) — в профиль доска, свисающая под горлом. У волка нижняя кромка морды поднимается к подбородку. Теперь высота
    # 0.20, центр тот же, и клин повёрнут на MUZZLE_TILT: у основания низ садится на низ головы (−0.11), у кончика — на
    # подбородок (−0.09), верх у кончика — на мочку. Мочка висит на Пасти и едет с ней
    m_a0, m_a1 = 0.095, L
    # ...ВЕРХ КЛИНА У ОСНОВАНИЯ НИЖЕ ЛБА (письмо механик 23.09b §2): при высоте 0.20 плоский верх клина шёл вровень с черепом
    # до уровня глаз (на 4 мм ниже темени) и анфас читался светлой планкой между глазами. У волка лоб сходит на спинку
    # носа скатом (стоп). Высота 0.18, центр ниже на 1 см: низ клина прежний, верх у основания ниже на 3 см — клин
    # уходит под лоб, и череп сам даёт скат
    m_h, m_w = 0.18, 0.14
    m_b0 = round((jaw_b + 0.002 + stop_b + 0.005) / 2 - 0.20 / 2, 3)
    m_b1 = round(m_b0 + m_h, 3)
    m_len = m_a1 - m_a0
    m_a, m_b = (m_a0 + m_a1) / 2, (m_b0 + m_b1) / 2

    # ГЛАЗ НА ПОВЕРХНОСТИ УЗЛА, а не «примерно сбоку»: полуширина узла `голова` на этой длине и высоте — из самого
    # графа (радиус сужается от r0 к r1, ширина × section). Глаз выступает на треть своего радиуса
    hn = next(n for n in G.build_nodes() if n['name'] == 'голова')
    h_len = math.dist(hn['a'], hn['b'])
    r_at = hn['r0'] + (hn['r1'] - hn['r0']) * min(1.0, max(0.0, eye_a / h_len))
    analytic = hn['section'] * math.sqrt(max(0.0, r_at * r_at - eye_b * eye_b))
    # ...НО ОБОЛОЧКА НЕ РАВНА РАСЧЁТУ, и разница зависит от клетки. Замер поверхности головы вбок в точке глаза (по вершинам
    # оболочки): 0.056 — 0.039 м (расчёт 0.041), 0.084 — 0.057, 0.042 — 0.061. Глаз садится центром НА поверхность:
    # при +0.005 он выходил из черепа на 1.4 см острым углом миндаля (письмо механик 17.09e §5 п. 4), теперь на ~0.9
    SURFACE_AT_EYE = {0.084: 0.057, 0.042: 0.061}
    eye_lat = round(SURFACE_AT_EYE[GRAIN], 3)

    places = [
        place('глаза', 0.5, eye_a, eye_b, eye_lat, (0.032, 0.032, 0.032),
              note='на поверхности узла `голова`: вбок — по его сечению на этой длине и высоте'),
        # Ухо стоит вертикально в мире: кадр головы наклонён носом вниз на 22°, наклон уха снят на столько же
        # УХО 12 см, основание 8.5 см (письмо механик 17.09e §5 п. 3): при 16.5 × 7.5 оно в профиль читалось тонким рогом.
        # Центр опущен на половину снятой высоты — основание осталось на черепе
        place('уши', 0.5, ear_a, ear_b - 0.022, 0.075, (0.085, 0.120, 0.035), euler=(-28.0, 45.0, -15.0),
              note='центр уха; основание и кончик рисует Чутьё долями этого места'),
        place('Пасть', 1.0, m_a, m_b, 0.0, (m_w, m_h, m_len), euler=(MUZZLE_TILT, 0.0, 0.0),
              note='коробка морды: клин + клыки; наклонена носом вниз'),
        place('Рога', 0.6, 0.08, 0.14, 0.06, (0.101, 0.127, 0.142),
              note='графт: над черепом за ушами; габарит прежний'),
    ]
    # МОЧКА ЕДЕТ С МОРДОЙ (ответ на вопрос механик 17.09d §6 п. 5). Мочка — конец морды: привили волку человечий Рот,
    # морды нет — мочке не место в воздухе перед лицом; привили человеку волчью Пасть — мочка обязана сесть на
    # кончик морды оборотня, а не остаться на лбу над ней. Поэтому доли мочки — от калибра ПАСТИ, а поле `parent`
    # — сверка: доли посчитаны от этого родителя (родство мест — запись механик, её перевешивают они)
    nose = dict(name='нос', parent='Пасть', attach=0.5,
                # мочка — на кончике клина: в долях коробки Пасти на той же высоте от её оси, что и в поставке 14 (0.09), а не от
                # точки снимка — клин опустился, и мочка по снимку повисла бы над кончиком
                attachOffset=[0.0, 0.09, round((nose_a - m_a) / m_len, 3)],
                sizeRel=list(rel((0.047, 0.040, 0.045), (m_w, m_h, m_len))), baseEuler=[0.0, 0.0, 0.0],
                note='мочка на конце клина; доли — от калибра Пасти',
                metres=dict(along=round(nose_a, 3), up=round(nose_b, 3), lateral=0.0, size=[0.047, 0.040, 0.045]))
    places.append(nose)
    return places, (m_w, m_h, m_len), (m_a, m_b)


def senses():
    """ПРИЗНАКИ ЧУВСТВ БЛОКАМИ (решение геймдизайнера 17.09: «нормальные, а не из примитивов»). Части органа Чутья по
    ролям, в калибре и кадре места-адреса. Цвет глаза не задаётся: это канал механики (чем зверь воспринимает мир).
      • ухо — блок заполняет место `уши` целиком: высота по Y, ширина по X, толщина по Z;
      • глаз — миндаль вдоль головы: у 3.2 см куба места он 1.8 × 1.9 × 4.2 см, половина тонет в черепе;
      • мочка — капля тупым концом вперёд, чуть приплюснута."""
    return [
        dict(role='Ear', block='ухо', offset=[0, 0, 0], scale=[1, 1, 1], euler=[0, 0, 0]),
        dict(role='Eye', block='глаз', offset=[0, 0, 0], scale=[0.56, 0.60, 1.30], euler=[0, 0, 0]),
        dict(role='Nose', block='капля', offset=[0, 0, 0], scale=[1.0, 0.85, 1.0], euler=[0, 0, 0]),
    ]


# КЛИН (`Tools/Blender/blocks.py`, `klin`): кольца (t, ширина, высота) вдоль оси, t от −0.5 (основание) до +0.5 (кончик)
KLIN = [(-0.50, 1.00, 1.00), (-0.10, 0.80, 0.76), (+0.50, 0.43, 0.40)]


def klin_at(t):
    for (t0, w0, h0), (t1, w1, h1) in zip(KLIN, KLIN[1:]):
        if t0 <= t <= t1:
            k = (t - t0) / (t1 - t0)
            return w0 + (w1 - w0) * k, h0 + (h1 - h0) * k
    return KLIN[-1][1:]


def teeth(muzzle, centre):
    """ЗУБЫ — ДВА ВЕРХНИХ КЛЫКА БЛОКОМ `игла` остриём вниз (письмо механик 17.09e §5 п. 1). Восемь кубов были единственными
    примитивами на теле; щёчные зубы выходили из боков сужающегося клина — в профиль квадраты на щеке, в анфас лесенка по
    низу морды. При закрытой пасти у волка видны только верхние клыки: они и оставлены. Клык сидит в кадре КОРОБКИ
    МОРДЫ (она наклонена — клык идёт за губой): на 1 см в клине, остриё на 2 см ниже нижней кромки, вбок — на 0.9 см
    внутри боковой кромки клина на этой длине."""
    W_, H_, L_ = muzzle
    ca, _ = centre
    white = [0.95, 0.94, 0.90, 1.0]
    along = 0.320                          # чуть позади подбородка (0.337)
    t = (along - ca) / L_
    kw, kh = klin_at(t)
    edge_y, edge_x = -kh * H_ / 2, kw * W_ / 2
    length, thick = 0.030, 0.014
    y = edge_y - length / 2 + 0.010
    out = []
    for side in (+1, -1):
        s = '(пр)' if side > 0 else '(лев)'
        out.append(dict(name='клык верхний ' + s, block='игла', euler=[180, 0, 0], color=white,
                        offset=[round(side * (edge_x - 0.009) / W_, 3), round(y / H_, 3), round(t, 3)],
                        scale=[round(thick / W_, 3), round(length / H_, 3), round(thick / L_, 3)]))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=os.path.join(HERE, 'out', 'volk-head-layout.json'))
    args = ap.parse_args()

    places, muzzle, centre = layout()
    head_size = (W, H, L)
    doc = dict(
        head=dict(baseSize=list(head_size), sizeRel=list(rel(head_size, NECK_CALIBRE))),
        places=places,
        muzzle=dict(block='клин', offset=[0, 0, 0], scale=[1, 1, 1]),
        teeth=teeth(muzzle, centre),
        senses=senses(),
    )
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, 'w', encoding='utf-8') as f:
        json.dump(doc, f, ensure_ascii=False, indent=2)
    # Плоская копия для проб в редакторе: сериализатор Unity не разбирает вложенные классы скрипта, собранного на лету
    f3 = lambda v: ','.join('%g' % x for x in v)
    with open(os.path.splitext(args.out)[0] + '.txt', 'w', encoding='utf-8') as f:
        f.write('head|%s|%s\n' % (f3(doc['head']['baseSize']), f3(doc['head']['sizeRel'])))
        for p in places:
            f.write('place|%s|%g|%s|%s|%s\n' % (p['name'], p['attach'], f3(p['attachOffset']), f3(p['sizeRel']), f3(p['baseEuler'])))
        f.write('muzzle|%s|%s|%s\n' % (doc['muzzle']['block'], f3(doc['muzzle']['offset']), f3(doc['muzzle']['scale'])))
        for t in doc['teeth']:
            f.write('tooth|%s|%s|%s|%s\n' % (t['name'], f3(t['offset']), f3(t['scale']), f3(t['color'])))

    print('калибр головы W×H×L = %.3f × %.3f × %.3f м; sizeRel от шеи = %s' % (head_size + (doc['head']['sizeRel'],)))
    for p in places:
        m = p['metres']
        print('  %-6s attach %.1f  offset %-24s sizeRel %-24s  (вдоль %.3f, к темени %.3f, вбок %.3f)%s' %
              (p['name'], p['attach'], p['attachOffset'], p['sizeRel'], m['along'], m['up'], m['lateral'],
               '  от места «%s»' % p['parent'] if 'parent' in p else ''))
    for t in doc['teeth']:
        print('    %-24s offset %-24s scale %s' % (t['name'], t['offset'], t['scale']))


if __name__ == '__main__':
    main()
