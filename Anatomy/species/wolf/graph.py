# ── ГЕОМЕТРИЯ → ПОЛЯ `Bone` ─────────────────────────────────────────────────────────────────────────
# Все узлы лежат в плоскости YZ (вынос по X — только смещение), поэтому поворот каждого — чистый Rx.
# Unity: Quaternion.Euler(x,0,0) разворачивает +Y к (0, cos x, sin x). Поворот наследуется: dir ребёнка =
# его мировой угол минус мировой угол родителя
def angle_of(a, b):
    dy, dz = b[1] - a[1], b[2] - a[2]
    return math.degrees(math.atan2(dz, dy))


def rx(deg, v):
    t = math.radians(deg)
    x, y, z = v
    return (x, y * math.cos(t) - z * math.sin(t), y * math.sin(t) + z * math.cos(t))


def dist(a, b):
    return math.sqrt(sum((p - q) ** 2 for p, q in zip(a, b)))


def to_bones(nodes):
    world = {}                       # имя → (начало, мировой угол, длина)
    out = []
    for n in nodes:
        a, b = n['a'], n['b']
        ang, length = angle_of(a, b), dist(a, b)
        bone = dict(name=n['name'], parent=n['parent'], layer=0, socket=n['socket'],
                    origin=dict(x=0.0, y=0.0, z=0.0), attach=1.0, freeOrigin=False,
                    length=round(length, 4), endBone='', endAttach=1.0,
                    dir=dict(x=0.0, y=0.0, z=0.0),
                    r0=n['r0'], r1=n['r1'], section=n['section'], depth=n['depth'],
                    blend=n['blend'], chain=0, mirrorX=n['mirror'])
        if not n['parent']:
            bone['origin'] = dict(x=round(a[0], 4), y=round(a[1], 4), z=round(a[2], 4))
            bone['dir']['x'] = round(ang, 3)
        else:
            pa, pang, plen = world[n['parent']]
            tip = (pa[0], pa[1] + plen * math.cos(math.radians(pang)), pa[2] + plen * math.sin(math.radians(pang)))
            if dist(a, tip) < 1e-4 and abs(a[0] - pa[0]) < 1e-6:
                bone['attach'] = 1.0            # сустав на конце родителя
            else:
                # начало не на конце родителя — смещение ОТ НАЧАЛА РОДИТЕЛЯ в его кадре
                d = (a[0] - pa[0], a[1] - pa[1], a[2] - pa[2])
                loc = rx(-pang, d)
                bone['freeOrigin'] = True
                bone['origin'] = dict(x=round(loc[0], 4), y=round(loc[1], 4), z=round(loc[2], 4))
            bone['dir']['x'] = round(ang - pang, 3)
        world[n['name']] = (a, ang, length)
        out.append(bone)
    return out


HIDES = ['хребет', 'шея', 'голова', 'Шкура', 'Сердце', 'Руки', 'Ноги', 'Хвост']


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=os.path.join(HERE, 'out', 'volk-graph-draft.json'))
    ap.add_argument('--preview-muzzle', action='store_true')
    args = ap.parse_args()

    nodes = build_nodes(args.preview_muzzle)
    bones = to_bones(nodes)
    doc = dict(species='Волк', hides=HIDES, nodes=bones)
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, 'w', encoding='utf-8') as f:
        json.dump(doc, f, ensure_ascii=False, indent=2)

    # сводка для глаза: где что стоит
    print('узлов', len(bones), '→', args.out)
    for n in nodes:
        print('  %-14s %-7s  (%.2f %.2f %.2f) → (%.2f %.2f %.2f)  r %.3f→%.3f' %
              ((n['name'], n['socket']) + tuple(n['a']) + tuple(n['b']) + (n['r0'], n['r1'])))


if __name__ == '__main__':
    main()
