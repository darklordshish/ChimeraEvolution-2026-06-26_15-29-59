"""СИЛУЭТНЫЙ ГРАФ ВОЛКА — поставка 2 модельной линии (`Docs/models/SPEC-priyomka-formy.md` §3).

ЧТО ЭТО. Не скелет, а ~20 ЖИРНЫХ узлов: узел отвечает «какой объём здесь есть и с кем он соединён».
Радиусы — это мясо и шерсть, а не кость. Формат узла — `Bone`, второго формата нет.

ОТКУДА ЧИСЛА. Суставы сняты с `ref/photo/wolf_standing_1.jpg` по сетке 50 px (кроп-сетки строятся тем же
приёмом, что `tools/grid.py`). Опоры снимка перемерены 17.09, а не взяты из `etalon/body.py`:
  земля      y = 1475 px  (низ лап; эталон 28.08 писал 1435 — это 4 см мимо)
  холка      y =  380 px, x = 1150 px
  масштаб    1.170 м / 1095 px — калибр игровой (холка 1.170), пропорции натуры
Координаты: Y от земли, Z вперёд к носу, X вбок (правая сторона; левую даёт mirrorX).

ОБЛИК — «СРЕДНИЙ» (решение геймдизайнера 17.09). Пропорции и суставы — с `_1` (летний волк: видны
кости и мышцы). Посадка головы — НЕЙТРАЛЬНАЯ, не настороженная, как на снимке (шея 28° вместо 43°):
поднятая голова и длинная шея и читались «ламой». Объём — умеренный, без гривы: грудь на 3 см глубже
летнего контура, остальное по контуру.

ЧЕГО В ГРАФЕ НЕТ НАМЕРЕННО. Морды, ушей, носа, когтей, пястей, плюсен и лап: это детали (метод §4.1), они приходят блоками на
свои места. Морда — деталь Пасти: иначе волчья Пасть на человеке не даст морды оборотня, а человечий Рот
на волке оставит ему волчью морду. Для просмотра есть флаг --preview-muzzle (узел НЕ для поставки).

ИМЕНА-ЯКОРЯ. `хребет`, `шея`, `голова` названы как места — под предложение §4.1 письма
`Docs/models/OTVET-2026-09-17-skeletonhides.md` (погашенное место берёт позу у одноимённого узла).
`крестец` и `грудной` сохранены: на них сейчас висят места `Хвост` и `Игломёт` (`attach` 1 и 0.5).

Запуск:  python graph.py [--out путь] [--preview-muzzle]
"""
