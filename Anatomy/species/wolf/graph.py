def node(name, socket, parent, a, b, r0, r1, section=1.0, depth=1.0, blend=0.0, mirror=False, layer=0, group=None, weld=0.0):
    d = dict(name=name, socket=socket, parent=parent, a=a, b=b, r0=r0, r1=r1,
             section=section, depth=depth, blend=blend, mirror=mirror, layer=layer)
    if group:
        d['group'] = group
    if weld:
        d['weld'] = weld
    return d


