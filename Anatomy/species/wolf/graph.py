S = 1.170 / (GROUND_PX - WITHERS_PX)


def px(x, y):
    """Пиксель снимка → (Z, Y) в метрах. Z = 0 посередине между седалищным бугром и плечевым."""
    return ((x - MID_X_PX) * S, (GROUND_PX - y) * S)


