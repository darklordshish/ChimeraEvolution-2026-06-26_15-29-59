# -*- coding: utf-8 -*-
"""ЭТАЛОННЫЙ КОНТУР ВОЛКА — СНЯТ С НАТУРЫ, а не собран из промеров.

Источник: ref/photo/wolf_standing_1.jpg (Викисклад, 2000x1501). Волк строго в профиль, стоит на
ровном помосте, все четыре лапы на земле, голова в спокойной настороженной стойке.

Почему не из литературы. Предыдущий эталон был собран из краниометрических таблиц и правил для
художников — и оказался ПЕРЕВЁРНУТ в главном: у волка в стойке голова ВЫШЕ линии спины (затылок на
1.20 высоты в холке), а выдуманный эталон вёл линию от холки вниз к носу. Модель сошлась с ним на
2.1 см и всё равно читалась неправильно. Одна фотография ловит это за секунду.

Как читать. Точки сняты по координатной сетке (`tools/grid.py`, шаг 100 px) и хранятся В ПИКСЕЛЯХ
ИСХОДНИКА — так их может перепроверить кто угодно, наложив ту же сетку. Перевод в метры идёт по
трём опорам ниже.
"""

# ── ОПОРЫ СНИМКА (пиксели исходника) ──────────────────────────────────────────────────────────────
GROUND_PX = 1435.0      # линия земли: низ лап
WITHERS_PX = 383.0      # холка: высшая точка спины над лопаткой
NOSE_X_PX = 1930.0      # кончик носа
WITHERS_X_PX = 1150.0   # холка по горизонтали
SCALE_PX = GROUND_PX - WITHERS_PX      # высота в холке = 1052 px — вся мера снимка

# ── ИГРОВОЙ КАЛИБР ────────────────────────────────────────────────────────────────────────────────
# Высота в холке у нашего волка. Пропорции берём с натуры, КАЛИБР остаётся игровым: это решение
# дизайнера, а не фотографии
WITHERS_M = 1.170
# Холка в наших координатах по Z — к ней привязан горизонт снимка
WITHERS_Z = 0.280

def to_model(x_px, y_px):
    """Пиксель снимка → метры нашей системы (Y от земли, Z вперёд к носу)."""
    s = WITHERS_M / SCALE_PX
    return ((x_px - WITHERS_X_PX) * s + WITHERS_Z, (GROUND_PX - y_px) * s)

# ── ВЕРХНЯЯ ЛИНИЯ: корень хвоста → круп → спина → холка → загривок → затылок → лоб → нос ──────────
TOP_PX = [(300, 480), (380, 410), (600, 390), (900, 383), (1150, 383), (1330, 355),
          (1480, 270), (1620, 180), (1700, 175), (1780, 235), (1850, 300), (1930, 375)]

# ── НИЖНЯЯ ЛИНИЯ: зад → пах → живот → низ груди → преднагрудье → низ шеи → горло → челюсть → нос ──
BOT_PX = [(450, 800), (600, 760), (900, 800), (1150, 830), (1380, 700), (1500, 570),
          (1650, 480), (1790, 455), (1880, 450), (1935, 420)]

# ── ЧТО ЭТИ ТОЧКИ ГОВОРЯТ (доли высоты в холке) ───────────────────────────────────────────────────
# затылок              1.195   ← ВЫШЕ ХОЛКИ. Ключевое расхождение с прежней моделью (было 0.838)
# темя                 1.200
# кончик носа, верх    1.010   ← нос примерно на уровне холки
# мочка, низ           0.967
# основание шеи, верх  1.029
# спина, перепад       0.021   ← спина почти ровная: круп ниже холки всего на 2%
# низ груди            0.576   ← глубина груди 0.424, просвет под грудью 0.576: волк долгоногий
# длина головы         0.300   (затылок → нос по горизонтали)
#
# ОГОВОРКА О ДЛИНЕ. Если совместить снимок по носу и корню хвоста, высота в холке даёт 1.098 м —
# то есть наше тело на ~6% короче натуры при той же холке. Это не ошибка позы, а КАЛИБР: правится
# отдельным решением, вместе с длиной позвоночника, и не смешивается со слоем костей.

TOP = [to_model(x, y) for x, y in TOP_PX]
BOT = [to_model(x, y) for x, y in BOT_PX]

if __name__ == '__main__':
    print('верх:', ', '.join('(%+.2f, %.2f)' % p for p in TOP))
    print('низ: ', ', '.join('(%+.2f, %.2f)' % p for p in BOT))
