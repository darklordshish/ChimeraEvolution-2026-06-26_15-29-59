def aim(Rpar, a, b):
    """Какой `dir` и `length` нужны, чтобы кость из точки a смотрела в b при повороте родителя Rpar."""
    v = np.array(b, dtype=float) - np.array(a, dtype=float)
    L = np.linalg.norm(v)
    vl = np.linalg.inv(Rpar) @ (v / L)
    z = -math.degrees(math.asin(max(-1.0, min(1.0, vl[0]))))
    x = math.degrees(math.atan2(vl[2], vl[1]))
    return (round(x, 1), 0.0, round(z, 1)), round(L, 3)

