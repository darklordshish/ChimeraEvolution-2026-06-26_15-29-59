# ПРОФИЛЬ СИЛУЭТА: верх и низ нарисованного по срезам Z. Читается как вид сбоку — по нему видно и
# провал талии, и разрыв между грудью и тазом, и то, тонет ли шея в холке
print()
print('ПРОФИЛЬ (срез по Z: верх / низ / высота корпуса)')
allsph = []
for b in bones:
    avg = max(0.001, (b.r0 + b.r1) * 0.5)
    segs = max(2, min(12, int(round(b.length / avg))))
    for i in range(segs + 1):
        t = i / float(segs)
        c = pos[b.name] + rot[b.name] @ (UP * (b.length * t))
        allsph.append((c, b.r0 + (b.r1 - b.r0) * t, b.name))
z = -0.70
while z <= 0.85:
    hits = [(c[1] + r, c[1] - r) for c, r, nm in allsph
            if abs(c[2] - z) < r and nm not in ('плечо', 'предплечье', 'пясть', 'лапа',
                                                'бедро', 'голень', 'плюсна', 'лапа_з')]
    if hits:
        hi = max(h for h, _ in hits); lo = min(l for _, l in hits)
        bar = ' ' * int((lo + 0.2) * 18) + '#' * max(1, int((hi - lo) * 18))
        print('Z %+.2f   верх %.3f  низ %.3f  h %.3f  %s' % (z, hi, lo, hi - lo, bar))
    z += 0.10

# АДРЕСА ОСТАВШИХСЯ МЕСТ: голова, хвост и игломёт живут сокетами и садятся на кость — считаем их
# смещения В МЕТРАХ в системе кости-родителя, чтобы части встали ровно туда, где стояли
print()
print('── СМЕЩЕНИЯ ДЛЯ МЕСТ НА КОСТЯХ (attachOffset, метры) ──')
#     ХВОСТ САДИТСЯ В НАЧАЛО КРЕСТЦА, БЕЗ СМЕЩЕНИЯ. Он продолжение позвоночника, а не деталь, которую
# прикладывают к крупу: любое смещение здесь — это будущая щель, потому что цепь уходит от точки прочь
# от тела. Прежние +0.05 по вертикали выносили первое звено ВЫШЕ мяса крестца — оно и висело отдельно
for nm, bone, att, target in (('голова',  'шея',     1.00, H((0.000, 1.055, 0.965))),
                              ('Хвост',   'крестец', 0.00, tuple(P['крестец'])),
                              ('Игломёт', 'грудной', 0.50, (0.000, 1.230,  0.230))):
    b = by[bone]
    base = pos[bone] + rot[bone] @ (UP * (b.length * att))
    # та же поправка, что в билдере: смещение и поворот места считаются в осях ТЕЛА, а не роста кости
    body = rot[bone] @ euler((-90, 0, 0))
    off = np.linalg.inv(body) @ (np.array(target) - base)
    tilt = math.degrees(math.atan2(-(body @ np.array([0.0, 0.0, 1.0]))[1], 1.0))
    print('%-9s на кости %-9s attach %.2f  ->  attachOffset (%.3f, %.3f, %.3f)   наклон осей тела %+.1f°'
          % (nm, bone, att, off[0], off[1], off[2], tilt))

# СТЫК ХВОСТА — ЗАМЕР, А НЕ ГЛАЗ. Первое звено цепи центрируется на половине своей длины от точки
# места; проверяем, что оно ВНУТРИ мяса крестца, иначе хвост висит отдельно от крупа
link_len, link_d = 0.088, 0.130
tail_dir = -33.2 + (-4.8)          # свес плюс наклон осей тела
tp = np.array(P['крестец'], dtype=float)
first = tp + np.array([0.0,
                       -math.sin(math.radians(-tail_dir)) * link_len * 0.5,
                       -math.cos(math.radians(-tail_dir)) * link_len * 0.5])
kr = by['крестец']
near = min(np.linalg.norm(first - (pos['крестец'] + rot['крестец'] @ (UP * (kr.length * i / 4.0))))
           - (kr.r0 + (kr.r1 - kr.r0) * i / 4.0) - link_d * 0.5 for i in range(5))
print()
print('СТЫК ХВОСТА: первое звено в (%.3f, %.3f, %.3f); зазор до мяса крестца %+.3f  %s'
      % (first[0], first[1], first[2], near, 'внутри тела — ok' if near < 0 else 'ЩЕЛЬ'))

# ОДНО ИМЯ В ДВУХ СЛОЯХ — НЕ ОШИБКА, НО ВОПРОС. Суффикс развёл адреса, и столкнуться они больше не
# могут; чего он не лечит — это когда одну и ту же мышцу описали дважды, литеральным объёмом и
# натянутой между костями. Так и было у жевательной: обе рисовались, морда выходила раздутой
_base = {}
for x in bones: _base.setdefault(x.name.split('.')[0], []).append(x.layer)
_multi = {k: v for k, v in _base.items() if len(v) > 1}
if _multi:
    print('?  ОДНО ИМЯ В РАЗНЫХ СЛОЯХ: %s — проверь, не описано ли одно тело дважды'
          % ', '.join('%s (слои %s)' % (k, '+'.join(map(str, v))) for k, v in _multi.items()))

