def top_at(zmin, zmax):
    """Верх нарисованного в диапазоне Z — так меряются холка и круп."""
    def f(by, pos, rot):
        best = -9
        for b in by.values():
            avg = max(0.001, (b.r0 + b.r1) * 0.5)
            segs = max(2, min(12, int(round(b.length / avg))))
            for i in range(segs + 1):
                t = i / float(segs)
                c = pos[b.name] + rot[b.name] @ (UP * (b.length * t))
                r = b.r0 + (b.r1 - b.r0) * t
                if zmin <= c[2] <= zmax: best = max(best, c[1] + r)
        return best
    return f

def bottom_of(name):
    def f(by, pos, rot):
        b = by[name]
        avg = max(0.001, (b.r0 + b.r1) * 0.5)
        segs = max(2, min(12, int(round(b.length / avg))))
        return min(pos[b.name][1] + (rot[b.name] @ (UP * (b.length * i / float(segs))))[1]
                   - (b.r0 + (b.r1 - b.r0) * i / float(segs)) for i in range(segs + 1))
    return f

def width_of(name):
    def f(by, pos, rot):
        b = by[name]
        avg = max(0.001, (b.r0 + b.r1) * 0.5)
        segs = max(2, min(12, int(round(b.length / avg))))
        return 2 * max(abs((pos[b.name] + rot[b.name] @ (UP * (b.length * i / float(segs))))[0])
                       + (b.r0 + (b.r1 - b.r0) * i / float(segs)) * b.section for i in range(segs + 1))
    return f

def span_z(names):
    """Длина группы костей по Z — так меряется череп: от затылка до мочки, с мясом."""
    def f(by, pos, rot):
        lo, hi = 9, -9
        for nm in names:
            b = by[nm]
            avg = max(0.001, (b.r0 + b.r1) * 0.5); segs = max(2, min(12, int(round(b.length / avg))))
            for i in range(segs + 1):
                t = i / float(segs); r = b.r0 + (b.r1 - b.r0) * t
                c = pos[nm] + rot[nm] @ (UP * (b.length * t))
                lo = min(lo, c[2] - r); hi = max(hi, c[2] + r)
        return hi - lo
    return f

def buried(point, own_r=0.0):
    """НА ЧЁМ СИДИТ МЕСТО. Отрицательное — точка внутри мяса, положительное — ВИСИТ В ВОЗДУХЕ.
    Раньше это ловилось только глазами на скриншоте: «глаза в воздухе висят» — и стоило трёх итераций."""
    def f(by, pos, rot):
        best = 9
        for b in by.values():
            avg = max(0.001, (b.r0 + b.r1) * 0.5); segs = max(2, min(12, int(round(b.length / avg))))
            for i in range(segs + 1):
                t = i / float(segs); r = b.r0 + (b.r1 - b.r0) * t
                c = pos[b.name] + rot[b.name] @ (UP * (b.length * t))
                for sgn in ((1, -1) if b.mirror else (1,)):
                    cc = np.array([c[0] * sgn, c[1], c[2]])
                    # СЕЧЕНИЕ УЧИТЫВАЕТСЯ: деталь не шар, а эллипсоид с полуосями (r*section, r, r).
                    # Без этого проверка врёт ровно там, где `section` велик — на коробке черепа (1.15),
                    # то есть на самой голове, где и стоят места чувств
                    d = np.array(point) - cc
                    d[0] /= max(0.001, b.section)
                    best = min(best, np.linalg.norm(d) - r)
        return best - own_r
    return f

