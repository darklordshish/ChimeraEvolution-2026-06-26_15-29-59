def H(p):
    """Точка головы: едет за затылочным суставом и доворачивается вокруг него."""
    q = np.array(p, dtype=float) + np.array([0.0, NECK_TIP_DROP, 0.0])
    if HEAD_PITCH:
        a = math.radians(HEAD_PITCH); c, sn = math.cos(a), math.sin(a)
        v = q - HEAD_PIVOT
        q = HEAD_PIVOT + np.array([v[0], c * v[1] + sn * v[2], -sn * v[1] + c * v[2]])
    return tuple(q)

