    """ДОЛЯ ХОЛКИ — так задана вся остеометрия: длины костей волка публикуются в мм, но сравнимы только
    через рост. Держим их проверкой, иначе кости «на глаз» уезжают на треть и это видно лишь боком."""
    return lambda by, pos, rot: by[name].length / 1.170

