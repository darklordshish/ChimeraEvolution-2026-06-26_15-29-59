LAYER_SUF = ('', '.м', '.п', '.р')       # скелет · мышца · признак · рез

_B = B
def B(name, parent='', **kw):
    """Кость: адрес получает суффикс своего слоя, ссылки пишутся анатомическим именем."""
    nm = name + LAYER_SUF[kw.get('layer', 0)]
    if parent: parent = ref(parent)
    if kw.get('endBone'): kw['endBone'] = ref(kw['endBone'])
    return _B(nm, parent, **kw)

def ref(x):
    """Анатомическое имя → реальный адрес кости. Ссылаются почти всегда на скелет, но если цель
    живёт только в одном слое, найдём и её; двусмысленность — повод упасть, а не угадывать."""
    if any(b.name == x for b in bones): return x
    cand = [b.name for b in bones if b.name.split('.')[0] == x]
    if not cand: return x                            # ещё не создана — поймает проверка в build
    if len(cand) > 1:
        raise SystemExit('ссылка «%s» неоднозначна: %s — уточни слой' % (x, ', '.join(cand)))
    return cand[0]

bones = []
def add(name, parent, a, b, r0, r1, section=1.0, mirror=False, socket='', attach=1.0, depth=1.0, blend=0.0, layer=0):
    """Кость от точки a до точки b: углы и длина считаются, в данные пойдут они."""
    _, pos, rot = build(bones) if bones else (None, {}, {})
    parent = ref(parent) if parent else parent
    Rpar = rot[parent] if parent else np.eye(3)
    d, L = aim(Rpar, P[a], P[b])
    bn = B(name, parent, origin=P[a] if not parent else (0, 0, 0), attach=attach, length=L,
           dir=d, r0=r0, r1=r1, section=section, mirror=mirror, socket=socket, depth=depth, blend=blend, layer=layer)
    bones.append(bn)
    # СВЕРКА: кость обязана прийти ровно в целевую точку — иначе данные разъехались с анатомией
    _, pos2, rot2 = build(bones)
    got = tip(bn, pos2, rot2)
    err = np.linalg.norm(got - np.array(P[b]))
    if err > 0.002:
        print('!! %s не попала в %s: ошибка %.4f' % (name, b, err))
    return bn

