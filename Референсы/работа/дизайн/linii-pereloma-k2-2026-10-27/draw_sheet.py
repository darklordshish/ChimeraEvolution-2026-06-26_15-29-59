def txt(im, xy, s, n=25, color=FG, bold=False):
    ImageDraw.Draw(im).text(xy, s, fill=color, font=font(n,bold))

def line(im, pts, color, width=5, dashed=False):
    d=ImageDraw.Draw(im)
    if dashed:
        import math
        for a,b in zip(pts,pts[1:]):
            length=math.dist(a,b)
            for i in range(0,int(length),16):
                j=min(i+9,length)
                p=[(a[0]+(b[0]-a[0])*t/length,a[1]+(b[1]-a[1])*t/length) for t in (i,j)]
                d.line(p,fill=BG,width=width+3)
                d.line(p,fill=color,width=width)
    else:
        d.line(pts,fill=BG,width=width+3,joint='curve')
        d.line(pts,fill=color,width=width,joint='curve')

