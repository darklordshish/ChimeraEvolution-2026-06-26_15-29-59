def render_panel(key):
    item=DATA[key]; box=item['box']; scale=2.6
    im=Image.new('RGB',(610,1510),BG)
    txt(im,(25,20),item['title'],32,bold=True)
    src=Image.open(SRC/'человек/вид.png').convert('RGB').crop(box)
    src=ImageEnhance.Contrast(src).enhance(.78)
    size=(round(src.width*scale),round(src.height*scale)); src=src.resize(size,Image.Resampling.LANCZOS)
    x=(610-size[0])//2; y=94
    im.paste(src,(x,y))
    def tr(p):return (round(x+(p[0]-box[0])*scale),round(y+(p[1]-box[1])*scale))
    for entry in item['lines']:
        name,pts=entry[:2]
        line(im,[tr(p) for p in pts],MAIN if name[0]=='Г' else SECOND,6 if name[0]=='Г' else 4,len(entry)>2)
    for name,p in item['tags']:
        px,py=tr(p)
        color=MAIN if name[0]=='Г' else SECOND
        w=font(22,True).getlength(name)+10
        ImageDraw.Draw(im).rounded_rectangle((px-2,py-12,px+w,py+16),4,fill=BG)
        txt(im,(px+3,py-10),name,22,color,True)
    if key in ('profile','back'):
        txt(im,(25,1390),'Г4 пунктир: скрыто шортами.',23,MUTED)
        txt(im,(25,1423),'Ход — по карте мышц; проверить на К2.',23,MUTED)
    else:
        txt(im,(25,1390),'Под шортами линии не восстанавливать',23,MUTED)
        txt(im,(25,1423),'по границам одежды.',23,MUTED)
    im.save(OUT/f'k2-{key}.png')
    return im

